CREATE OR REPLACE FUNCTION proteger_detalle_conteo_inventario()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Las partidas de conteo son inmutables.' USING ERRCODE = '55000';
  END IF;
  IF NEW.id <> OLD.id
     OR NEW.conteo_inventario_id <> OLD.conteo_inventario_id
     OR NEW.producto_id <> OLD.producto_id
     OR NEW.producto_sku <> OLD.producto_sku
     OR NEW.producto_titulo <> OLD.producto_titulo
     OR NEW.stock_fisico_al_abrir <> OLD.stock_fisico_al_abrir
     OR NEW.stock_reservado_al_abrir <> OLD.stock_reservado_al_abrir
     OR NEW.movimiento_al_abrir_id IS DISTINCT FROM OLD.movimiento_al_abrir_id
     OR NEW.creado_en <> OLD.creado_en THEN
    RAISE EXCEPTION 'No se puede modificar el snapshot de la partida.' USING ERRCODE = '55000';
  END IF;
  IF OLD.captura_aplicada_id IS NOT NULL
     OR NEW.captura_aplicada_id IS NULL
     OR NEW.diferencia_aplicada IS NULL
     OR NEW.stock_fisico_aplicado IS NULL
     OR NEW.stock_reservado_aplicado IS NULL THEN
    RAISE EXCEPTION 'La aplicación de una partida sólo puede registrarse una vez.' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$function$;

CREATE TRIGGER detalle_conteos_inventario_proteger_trg
  BEFORE UPDATE OR DELETE ON detalle_conteos_inventario
  FOR EACH ROW EXECUTE FUNCTION proteger_detalle_conteo_inventario();

CREATE OR REPLACE FUNCTION validar_conteo_inventario_conciliado(p_conteo_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $function$
DECLARE
  v_conteo conteos_inventario%ROWTYPE;
  v_lineas INTEGER;
  v_ultima_transicion VARCHAR(12);
BEGIN
  SELECT * INTO v_conteo FROM conteos_inventario WHERE id = p_conteo_id;
  IF NOT FOUND THEN RETURN; END IF;

  SELECT COUNT(*) INTO v_lineas
  FROM detalle_conteos_inventario WHERE conteo_inventario_id = p_conteo_id;
  IF v_lineas = 0 THEN
    RAISE EXCEPTION 'El conteo % no contiene partidas.', p_conteo_id USING ERRCODE = '23514';
  END IF;

  SELECT estado_nuevo INTO v_ultima_transicion
  FROM conteo_inventario_transiciones
  WHERE conteo_inventario_id = p_conteo_id
  ORDER BY id DESC LIMIT 1;
  IF v_ultima_transicion IS DISTINCT FROM v_conteo.estado THEN
    RAISE EXCEPTION 'El historial del conteo % no coincide con su estado.', p_conteo_id
      USING ERRCODE = '23514';
  END IF;

  IF v_conteo.estado IN ('BORRADOR', 'CANCELADO') THEN
    IF EXISTS (
      SELECT 1 FROM detalle_conteos_inventario
      WHERE conteo_inventario_id = p_conteo_id
        AND captura_aplicada_id IS NOT NULL
    ) OR EXISTS (
      SELECT 1 FROM inventario_movimientos
      WHERE conteo_inventario_id = p_conteo_id
    ) THEN
      RAISE EXCEPTION 'El conteo % no aplicado contiene efectos de inventario.', p_conteo_id
        USING ERRCODE = '23514';
    END IF;
    RETURN;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM detalle_conteos_inventario d
    LEFT JOIN capturas_conteo_inventario c ON c.id = d.captura_aplicada_id
    LEFT JOIN inventario_movimientos im
      ON im.detalle_conteo_inventario_id = d.id AND im.tipo = 'CONTEO'
    WHERE d.conteo_inventario_id = p_conteo_id
      AND (
        c.id IS NULL
        OR c.detalle_conteo_inventario_id <> d.id
        OR c.conteo_inventario_id <> d.conteo_inventario_id
        OR c.producto_id <> d.producto_id
        OR d.diferencia_aplicada <> c.cantidad_contada - c.stock_fisico_base
        OR d.stock_fisico_aplicado <> c.cantidad_contada
        OR d.stock_reservado_aplicado <> c.stock_reservado_base
        OR (d.diferencia_aplicada = 0 AND im.id IS NOT NULL)
        OR (
          d.diferencia_aplicada <> 0
          AND (
            im.id IS NULL OR im.producto_id <> d.producto_id
            OR im.conteo_inventario_id <> d.conteo_inventario_id
            OR im.delta_fisico <> d.diferencia_aplicada OR im.delta_reservado <> 0
            OR im.stock_fisico_resultante <> d.stock_fisico_aplicado
            OR im.stock_reservado_resultante <> d.stock_reservado_aplicado
          )
        )
      )
  ) THEN
    RAISE EXCEPTION 'Las partidas aplicadas del conteo % no están conciliadas.', p_conteo_id
      USING ERRCODE = '23514';
  END IF;
END
$function$;

CREATE OR REPLACE FUNCTION validar_conteo_inventario_conciliado_trg()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
  v_id BIGINT;
BEGIN
  IF TG_TABLE_NAME = 'conteos_inventario' THEN
    v_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END;
  ELSIF TG_TABLE_NAME = 'detalle_conteos_inventario' THEN
    v_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.conteo_inventario_id ELSE NEW.conteo_inventario_id END;
  ELSIF TG_TABLE_NAME = 'conteo_inventario_transiciones' THEN
    v_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.conteo_inventario_id ELSE NEW.conteo_inventario_id END;
  ELSE
    v_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.conteo_inventario_id ELSE NEW.conteo_inventario_id END;
  END IF;
  PERFORM validar_conteo_inventario_conciliado(v_id);
  RETURN NULL;
END
$function$;

CREATE CONSTRAINT TRIGGER conteos_inventario_conciliacion_trg
  AFTER INSERT OR UPDATE ON conteos_inventario DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_conteo_inventario_conciliado_trg();
CREATE CONSTRAINT TRIGGER detalle_conteos_inventario_conciliacion_trg
  AFTER INSERT OR UPDATE ON detalle_conteos_inventario DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_conteo_inventario_conciliado_trg();
CREATE CONSTRAINT TRIGGER conteo_inventario_transiciones_conciliacion_trg
  AFTER INSERT ON conteo_inventario_transiciones DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_conteo_inventario_conciliado_trg();
CREATE CONSTRAINT TRIGGER inventario_conteo_conciliacion_trg
  AFTER INSERT ON inventario_movimientos DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW
  WHEN (NEW.conteo_inventario_id IS NOT NULL)
  EXECUTE FUNCTION validar_conteo_inventario_conciliado_trg();
