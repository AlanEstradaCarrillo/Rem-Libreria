-- Reposición y conteos para una sola existencia omnicanal.
-- Las sugerencias consideran stock disponible y órdenes de compra en tránsito.
-- Un conteo sólo puede aplicarse si ningún movimiento ocurrió después de su captura.

CREATE TABLE politicas_reposicion (
  producto_id INTEGER PRIMARY KEY REFERENCES productos(id) ON DELETE RESTRICT,
  stock_minimo INTEGER NOT NULL DEFAULT 0,
  stock_objetivo INTEGER NOT NULL DEFAULT 0,
  proveedor_preferido_id BIGINT REFERENCES proveedores(id) ON DELETE RESTRICT,
  creado_por_usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  actualizado_por_usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT politicas_reposicion_minimo_check CHECK (
    stock_minimo BETWEEN 0 AND 1000000
  ),
  CONSTRAINT politicas_reposicion_objetivo_check CHECK (
    stock_objetivo BETWEEN stock_minimo AND 1000000
  )
);

CREATE INDEX politicas_reposicion_proveedor_idx
  ON politicas_reposicion (proveedor_preferido_id, producto_id)
  WHERE proveedor_preferido_id IS NOT NULL;

CREATE TABLE politicas_reposicion_historial (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id INTEGER NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
  stock_minimo_anterior INTEGER,
  stock_objetivo_anterior INTEGER,
  proveedor_anterior_id BIGINT REFERENCES proveedores(id) ON DELETE RESTRICT,
  stock_minimo_nuevo INTEGER NOT NULL,
  stock_objetivo_nuevo INTEGER NOT NULL,
  proveedor_nuevo_id BIGINT REFERENCES proveedores(id) ON DELETE RESTRICT,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  motivo VARCHAR(240) NOT NULL,
  origen_clave VARCHAR(180) NOT NULL UNIQUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT politicas_reposicion_historial_anterior_check CHECK (
    (stock_minimo_anterior IS NULL AND stock_objetivo_anterior IS NULL)
    OR (
      stock_minimo_anterior BETWEEN 0 AND 1000000
      AND stock_objetivo_anterior BETWEEN stock_minimo_anterior AND 1000000
    )
  ),
  CONSTRAINT politicas_reposicion_historial_nuevo_check CHECK (
    stock_minimo_nuevo BETWEEN 0 AND 1000000
    AND stock_objetivo_nuevo BETWEEN stock_minimo_nuevo AND 1000000
  ),
  CONSTRAINT politicas_reposicion_historial_motivo_check CHECK (btrim(motivo) <> ''),
  CONSTRAINT politicas_reposicion_historial_origen_check CHECK (btrim(origen_clave) <> '')
);

CREATE INDEX politicas_reposicion_historial_producto_idx
  ON politicas_reposicion_historial (producto_id, id DESC);

CREATE SEQUENCE conteos_inventario_folio_seq START WITH 1;

CREATE TABLE conteos_inventario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio VARCHAR(24) NOT NULL UNIQUE
    DEFAULT ('CI-' || LPAD(nextval('conteos_inventario_folio_seq')::text, 10, '0')),
  estado VARCHAR(12) NOT NULL DEFAULT 'BORRADOR',
  notas TEXT,
  creado_por_usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  aplicado_por_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  aplicado_en TIMESTAMPTZ,
  cancelado_por_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  cancelado_en TIMESTAMPTZ,
  cancelacion_motivo VARCHAR(240),
  CONSTRAINT conteos_inventario_estado_check CHECK (
    estado IN ('BORRADOR', 'APLICADO', 'CANCELADO')
  ),
  CONSTRAINT conteos_inventario_notas_check CHECK (
    notas IS NULL OR btrim(notas) <> ''
  ),
  CONSTRAINT conteos_inventario_estado_datos_check CHECK (
    (
      estado = 'BORRADOR'
      AND aplicado_por_usuario_id IS NULL AND aplicado_en IS NULL
      AND cancelado_por_usuario_id IS NULL AND cancelado_en IS NULL
      AND cancelacion_motivo IS NULL
    )
    OR (
      estado = 'APLICADO'
      AND aplicado_por_usuario_id IS NOT NULL AND aplicado_en IS NOT NULL
      AND cancelado_por_usuario_id IS NULL AND cancelado_en IS NULL
      AND cancelacion_motivo IS NULL
    )
    OR (
      estado = 'CANCELADO'
      AND aplicado_por_usuario_id IS NULL AND aplicado_en IS NULL
      AND cancelado_por_usuario_id IS NOT NULL AND cancelado_en IS NOT NULL
      AND btrim(COALESCE(cancelacion_motivo, '')) <> ''
    )
  )
);

CREATE INDEX conteos_inventario_estado_fecha_idx
