CREATE OR REPLACE FUNCTION validar_politica_reposicion_auditada(p_producto_id INTEGER)
RETURNS VOID
LANGUAGE plpgsql
AS $function$
DECLARE
  v_politica politicas_reposicion%ROWTYPE;
  v_historial politicas_reposicion_historial%ROWTYPE;
BEGIN
  SELECT * INTO v_politica FROM politicas_reposicion WHERE producto_id=p_producto_id;
  IF NOT FOUND THEN RETURN; END IF;
  SELECT * INTO v_historial
  FROM politicas_reposicion_historial
  WHERE producto_id=p_producto_id ORDER BY id DESC LIMIT 1;
  IF NOT FOUND
     OR v_historial.stock_minimo_nuevo <> v_politica.stock_minimo
     OR v_historial.stock_objetivo_nuevo <> v_politica.stock_objetivo
     OR v_historial.proveedor_nuevo_id IS DISTINCT FROM v_politica.proveedor_preferido_id
     OR v_historial.usuario_id <> v_politica.actualizado_por_usuario_id THEN
    RAISE EXCEPTION 'La política de reposición % carece de auditoría conciliada.', p_producto_id
      USING ERRCODE = '23514';
  END IF;
END
$function$;

CREATE OR REPLACE FUNCTION validar_politica_reposicion_auditada_trg()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  PERFORM validar_politica_reposicion_auditada(
    CASE WHEN TG_OP='DELETE' THEN OLD.producto_id ELSE NEW.producto_id END
  );
  RETURN NULL;
END
$function$;

CREATE CONSTRAINT TRIGGER politicas_reposicion_auditoria_trg
  AFTER INSERT OR UPDATE ON politicas_reposicion DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_politica_reposicion_auditada_trg();
CREATE CONSTRAINT TRIGGER politicas_reposicion_historial_conciliacion_trg
  AFTER INSERT ON politicas_reposicion_historial DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_politica_reposicion_auditada_trg();

CREATE OR REPLACE FUNCTION validar_captura_conteo_borrador()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
  v_estado VARCHAR(12);
BEGIN
  SELECT estado INTO v_estado
  FROM conteos_inventario
  WHERE id=NEW.conteo_inventario_id
  FOR KEY SHARE;
  IF v_estado IS DISTINCT FROM 'BORRADOR' THEN
    RAISE EXCEPTION 'Sólo un conteo en borrador acepta capturas.' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$function$;

CREATE TRIGGER capturas_conteo_inventario_estado_trg
  BEFORE INSERT ON capturas_conteo_inventario
  FOR EACH ROW EXECUTE FUNCTION validar_captura_conteo_borrador();

CREATE OR REPLACE FUNCTION proteger_conteo_inventario()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Los conteos no se eliminan; deben cancelarse.' USING ERRCODE = '55000';
  END IF;
  IF OLD.estado <> 'BORRADOR' THEN
    RAISE EXCEPTION 'Un conteo finalizado es inmutable.' USING ERRCODE = '55000';
  END IF;
  IF NEW.id <> OLD.id OR NEW.folio <> OLD.folio OR NEW.notas IS DISTINCT FROM OLD.notas
     OR NEW.creado_por_usuario_id <> OLD.creado_por_usuario_id
     OR NEW.creado_en <> OLD.creado_en THEN
    RAISE EXCEPTION 'No se puede modificar la identidad del conteo.' USING ERRCODE = '55000';
  END IF;
  IF NEW.estado = 'BORRADOR' THEN
    RETURN NEW;
  END IF;
  IF NEW.estado NOT IN ('APLICADO', 'CANCELADO') THEN
    RAISE EXCEPTION 'Transición de conteo no permitida.' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$function$;

