CREATE SEQUENCE liquidaciones_regalias_folio_seq START WITH 1;

CREATE TABLE liquidaciones_regalias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio VARCHAR(24) NOT NULL UNIQUE
    DEFAULT ('REG-' || LPAD(nextval('liquidaciones_regalias_folio_seq')::text, 10, '0')),
  contrato_editorial_id BIGINT NOT NULL
    REFERENCES contratos_editoriales(id) ON DELETE RESTRICT,
  version INTEGER NOT NULL,
  reemplaza_liquidacion_id BIGINT REFERENCES liquidaciones_regalias(id) ON DELETE RESTRICT,
  periodo_desde DATE NOT NULL,
  periodo_hasta DATE NOT NULL,
  zona_horaria VARCHAR(80) NOT NULL,
  estado VARCHAR(12) NOT NULL DEFAULT 'BORRADOR',
  contrato_folio VARCHAR(24) NOT NULL,
  obra_editorial_id BIGINT NOT NULL REFERENCES obras_editoriales(id) ON DELETE RESTRICT,
  obra_folio VARCHAR(24) NOT NULL,
  obra_titulo VARCHAR(240) NOT NULL,
  colaborador_editorial_id BIGINT NOT NULL
    REFERENCES colaboradores_editoriales(id) ON DELETE RESTRICT,
  colaborador_nombre VARCHAR(160) NOT NULL,
  base_regalia VARCHAR(20) NOT NULL,
  porcentaje_regalia NUMERIC(7,4) NOT NULL,
  moneda CHAR(3) NOT NULL,
  unidades_netas INTEGER NOT NULL,
  base_regalia_total NUMERIC(14,2) NOT NULL,
  regalia_bruta NUMERIC(14,2) NOT NULL,
  saldo_editorial_anterior NUMERIC(14,2) NOT NULL DEFAULT 0,
  saldo_editorial_aplicado NUMERIC(14,2) NOT NULL DEFAULT 0,
  saldo_editorial_nuevo NUMERIC(14,2) NOT NULL DEFAULT 0,
  anticipo_pendiente_antes NUMERIC(14,2) NOT NULL DEFAULT 0,
  anticipo_aplicado NUMERIC(14,2) NOT NULL DEFAULT 0,
  anticipo_pendiente_despues NUMERIC(14,2) NOT NULL DEFAULT 0,
  importe_pagable NUMERIC(14,2) NOT NULL DEFAULT 0,
  notas TEXT,
  creado_por_usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  emitido_por_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  emitido_en TIMESTAMPTZ,
  pagado_por_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  pagado_en TIMESTAMPTZ,
  pago_referencia VARCHAR(160),
  cancelado_por_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  cancelado_en TIMESTAMPTZ,
  cancelacion_motivo VARCHAR(500),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT liquidaciones_regalias_version_check CHECK (version > 0),
  CONSTRAINT liquidaciones_regalias_periodo_check CHECK (periodo_hasta > periodo_desde),
  CONSTRAINT liquidaciones_regalias_zona_check CHECK (btrim(zona_horaria) <> ''),
  CONSTRAINT liquidaciones_regalias_estado_check CHECK (
    estado IN ('BORRADOR', 'EMITIDA', 'PAGADA', 'CANCELADA')
  ),
  CONSTRAINT liquidaciones_regalias_snapshots_check CHECK (
    btrim(contrato_folio) <> '' AND btrim(obra_folio) <> ''
    AND btrim(obra_titulo) <> '' AND btrim(colaborador_nombre) <> ''
  ),
  CONSTRAINT liquidaciones_regalias_base_check CHECK (
    base_regalia IN ('VENTA_NETA', 'PRECIO_LISTA')
  ),
  CONSTRAINT liquidaciones_regalias_porcentaje_check CHECK (
    porcentaje_regalia BETWEEN 0 AND 100
  ),
  CONSTRAINT liquidaciones_regalias_moneda_check CHECK (moneda ~ '^[A-Z]{3}$'),
  CONSTRAINT liquidaciones_regalias_saldos_check CHECK (
    saldo_editorial_anterior >= 0
    AND saldo_editorial_aplicado >= 0
    AND saldo_editorial_nuevo >= 0
    AND saldo_editorial_aplicado <= saldo_editorial_anterior
    AND saldo_editorial_aplicado <= GREATEST(regalia_bruta, 0)
    AND saldo_editorial_nuevo = ROUND(
      saldo_editorial_anterior - saldo_editorial_aplicado
      + GREATEST(-regalia_bruta, 0),
      2
    )
  ),
  CONSTRAINT liquidaciones_regalias_anticipo_check CHECK (
    anticipo_pendiente_antes >= 0 AND anticipo_aplicado >= 0
    AND anticipo_pendiente_despues >= 0
    AND anticipo_aplicado <= anticipo_pendiente_antes
    AND anticipo_aplicado <= GREATEST(regalia_bruta - saldo_editorial_aplicado, 0)
    AND anticipo_pendiente_despues = ROUND(
      anticipo_pendiente_antes - anticipo_aplicado,
      2
    )
  ),
  CONSTRAINT liquidaciones_regalias_pagable_check CHECK (
    importe_pagable >= 0
    AND importe_pagable = GREATEST(
      ROUND(regalia_bruta - saldo_editorial_aplicado - anticipo_aplicado, 2),
      0
    )
  ),
  CONSTRAINT liquidaciones_regalias_notas_check CHECK (
    notas IS NULL OR btrim(notas) <> ''
  ),
  CONSTRAINT liquidaciones_regalias_pago_referencia_check CHECK (
    pago_referencia IS NULL OR btrim(pago_referencia) <> ''
  ),
  CONSTRAINT liquidaciones_regalias_cancelacion_motivo_check CHECK (
    cancelacion_motivo IS NULL OR btrim(cancelacion_motivo) <> ''
  ),
  CONSTRAINT liquidaciones_regalias_efectos_estado_check CHECK (
    (
      estado='BORRADOR'
      AND emitido_por_usuario_id IS NULL AND emitido_en IS NULL
      AND pagado_por_usuario_id IS NULL AND pagado_en IS NULL AND pago_referencia IS NULL
      AND cancelado_por_usuario_id IS NULL AND cancelado_en IS NULL
      AND cancelacion_motivo IS NULL
    )
    OR (
      estado='EMITIDA'
      AND emitido_por_usuario_id IS NOT NULL AND emitido_en IS NOT NULL
      AND pagado_por_usuario_id IS NULL AND pagado_en IS NULL AND pago_referencia IS NULL
      AND cancelado_por_usuario_id IS NULL AND cancelado_en IS NULL
      AND cancelacion_motivo IS NULL
    )
    OR (
      estado='PAGADA'
      AND emitido_por_usuario_id IS NOT NULL AND emitido_en IS NOT NULL
      AND pagado_por_usuario_id IS NOT NULL AND pagado_en IS NOT NULL
      AND pago_referencia IS NOT NULL
      AND cancelado_por_usuario_id IS NULL AND cancelado_en IS NULL
      AND cancelacion_motivo IS NULL
    )
    OR (
      estado='CANCELADA'
      AND pagado_por_usuario_id IS NULL AND pagado_en IS NULL AND pago_referencia IS NULL
      AND cancelado_por_usuario_id IS NOT NULL AND cancelado_en IS NOT NULL
      AND cancelacion_motivo IS NOT NULL
      AND (
        (emitido_por_usuario_id IS NULL AND emitido_en IS NULL)
        OR (emitido_por_usuario_id IS NOT NULL AND emitido_en IS NOT NULL)
      )
    )
  ),
  CONSTRAINT liquidaciones_regalias_periodo_version_uq
    UNIQUE (contrato_editorial_id, periodo_desde, periodo_hasta, version)
);

