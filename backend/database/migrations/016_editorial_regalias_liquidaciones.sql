CREATE OR REPLACE FUNCTION validar_periodo_liquidacion_regalia()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  PERFORM pg_advisory_xact_lock(
    hashtextextended('LIQUIDACION_REGALIA:' || NEW.contrato_editorial_id::text, 0)
  );
  IF EXISTS (
    SELECT 1 FROM liquidaciones_regalias l
    WHERE l.contrato_editorial_id=NEW.contrato_editorial_id
      AND l.estado <> 'CANCELADA'
      AND daterange(l.periodo_desde, l.periodo_hasta, '[)')
          && daterange(NEW.periodo_desde, NEW.periodo_hasta, '[)')
  ) THEN
    RAISE EXCEPTION 'El periodo se superpone con otra liquidación vigente.'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$function$;

CREATE TRIGGER liquidaciones_regalias_periodo_trg
  BEFORE INSERT ON liquidaciones_regalias
  FOR EACH ROW EXECUTE FUNCTION validar_periodo_liquidacion_regalia();

CREATE OR REPLACE FUNCTION validar_cadena_transicion_liquidacion_regalia()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
  v_ultimo VARCHAR(12);
BEGIN
  SELECT estado_nuevo INTO v_ultimo
  FROM liquidacion_regalia_transiciones
  WHERE liquidacion_regalia_id=NEW.liquidacion_regalia_id
  ORDER BY id DESC LIMIT 1;
  IF NEW.estado_anterior IS DISTINCT FROM v_ultimo THEN
    RAISE EXCEPTION 'La transición de la liquidación no continúa el historial.'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$function$;

CREATE TRIGGER liquidacion_regalia_transiciones_cadena_trg
  BEFORE INSERT ON liquidacion_regalia_transiciones
  FOR EACH ROW EXECUTE FUNCTION validar_cadena_transicion_liquidacion_regalia();

CREATE OR REPLACE FUNCTION proteger_liquidacion_regalia()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  IF TG_OP='DELETE' THEN
    RAISE EXCEPTION 'Las liquidaciones no se eliminan; deben cancelarse.'
      USING ERRCODE = '55000';
  END IF;
  IF NEW.id <> OLD.id OR NEW.folio <> OLD.folio
     OR NEW.contrato_editorial_id <> OLD.contrato_editorial_id
     OR NEW.version <> OLD.version
     OR NEW.reemplaza_liquidacion_id IS DISTINCT FROM OLD.reemplaza_liquidacion_id
     OR NEW.periodo_desde <> OLD.periodo_desde OR NEW.periodo_hasta <> OLD.periodo_hasta
     OR NEW.zona_horaria <> OLD.zona_horaria
     OR NEW.contrato_folio <> OLD.contrato_folio
     OR NEW.obra_editorial_id <> OLD.obra_editorial_id
     OR NEW.obra_folio <> OLD.obra_folio OR NEW.obra_titulo <> OLD.obra_titulo
     OR NEW.colaborador_editorial_id <> OLD.colaborador_editorial_id
     OR NEW.colaborador_nombre <> OLD.colaborador_nombre
     OR NEW.base_regalia <> OLD.base_regalia
     OR NEW.porcentaje_regalia <> OLD.porcentaje_regalia
     OR NEW.moneda <> OLD.moneda OR NEW.unidades_netas <> OLD.unidades_netas
     OR NEW.base_regalia_total <> OLD.base_regalia_total
     OR NEW.regalia_bruta <> OLD.regalia_bruta
     OR NEW.saldo_editorial_anterior <> OLD.saldo_editorial_anterior
     OR NEW.saldo_editorial_aplicado <> OLD.saldo_editorial_aplicado
     OR NEW.saldo_editorial_nuevo <> OLD.saldo_editorial_nuevo
     OR NEW.anticipo_pendiente_antes <> OLD.anticipo_pendiente_antes
     OR NEW.anticipo_aplicado <> OLD.anticipo_aplicado
     OR NEW.anticipo_pendiente_despues <> OLD.anticipo_pendiente_despues
     OR NEW.importe_pagable <> OLD.importe_pagable
     OR NEW.notas IS DISTINCT FROM OLD.notas
     OR NEW.creado_por_usuario_id <> OLD.creado_por_usuario_id
     OR NEW.creado_en <> OLD.creado_en THEN
    RAISE EXCEPTION 'El cálculo y los snapshots de la liquidación son inmutables.'
      USING ERRCODE = '55000';
  END IF;
  IF OLD.estado IN ('PAGADA','CANCELADA') THEN
    RAISE EXCEPTION 'Una liquidación finalizada es inmutable.' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$function$;

CREATE TRIGGER liquidaciones_regalias_proteger_trg
  BEFORE UPDATE OR DELETE ON liquidaciones_regalias
  FOR EACH ROW EXECUTE FUNCTION proteger_liquidacion_regalia();

CREATE OR REPLACE FUNCTION validar_liquidacion_regalia_conciliada(p_liquidacion_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $function$
DECLARE
  v_liquidacion liquidaciones_regalias%ROWTYPE;
  v_ultimo VARCHAR(12);
  v_unidades INTEGER;
  v_base NUMERIC(14,2);
  v_regalia NUMERIC(14,2);
BEGIN
  SELECT * INTO v_liquidacion FROM liquidaciones_regalias WHERE id=p_liquidacion_id;
  IF NOT FOUND THEN RETURN; END IF;
  SELECT estado_nuevo INTO v_ultimo
  FROM liquidacion_regalia_transiciones
  WHERE liquidacion_regalia_id=p_liquidacion_id ORDER BY id DESC LIMIT 1;
  IF v_ultimo IS DISTINCT FROM v_liquidacion.estado THEN
    RAISE EXCEPTION 'El historial de la liquidación % no coincide con su estado.', p_liquidacion_id
      USING ERRCODE = '23514';
  END IF;
  SELECT COALESCE(SUM(cantidad_neta),0)::int,
         COALESCE(ROUND(SUM(base_regalia),2),0),
         COALESCE(ROUND(SUM(importe_regalia),2),0)
  INTO v_unidades, v_base, v_regalia
  FROM detalle_liquidaciones_regalias
  WHERE liquidacion_regalia_id=p_liquidacion_id;
  IF v_unidades <> v_liquidacion.unidades_netas
     OR v_base <> v_liquidacion.base_regalia_total
     OR v_regalia <> v_liquidacion.regalia_bruta THEN
    RAISE EXCEPTION 'El detalle de la liquidación % no está conciliado.', p_liquidacion_id
      USING ERRCODE = '23514';
  END IF;
END
$function$;

CREATE OR REPLACE FUNCTION validar_liquidacion_regalia_conciliada_trg()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
  v_id BIGINT;
BEGIN
  IF TG_TABLE_NAME='liquidaciones_regalias' THEN
    v_id := CASE WHEN TG_OP='DELETE' THEN OLD.id ELSE NEW.id END;
  ELSE
    v_id := CASE WHEN TG_OP='DELETE' THEN OLD.liquidacion_regalia_id ELSE NEW.liquidacion_regalia_id END;
  END IF;
  PERFORM validar_liquidacion_regalia_conciliada(v_id);
  RETURN NULL;
END
$function$;

CREATE CONSTRAINT TRIGGER liquidaciones_regalias_conciliacion_trg
  AFTER INSERT OR UPDATE ON liquidaciones_regalias DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_liquidacion_regalia_conciliada_trg();
CREATE CONSTRAINT TRIGGER detalle_liquidaciones_regalias_conciliacion_trg
  AFTER INSERT ON detalle_liquidaciones_regalias DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_liquidacion_regalia_conciliada_trg();
CREATE CONSTRAINT TRIGGER liquidacion_regalia_transiciones_conciliacion_trg
  AFTER INSERT ON liquidacion_regalia_transiciones DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_liquidacion_regalia_conciliada_trg();
