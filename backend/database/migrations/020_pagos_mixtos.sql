-- Pagos mixtos: varios medios de pago por venta, cancelación o devolución.
-- Cada fila de movimiento_pagos es el importe de un medio dentro de un movimiento.
-- Los movimientos de venta, cancelación y devolución conservan un único registro,
-- así que las líneas comerciales no se duplican. Los importes de caja, corte y
-- flujo de efectivo se reparten por medio desde esta tabla.

CREATE TABLE IF NOT EXISTS movimiento_pagos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movimiento_id INTEGER NOT NULL REFERENCES movimientos(id) ON DELETE RESTRICT,
  metodo_pago VARCHAR(20) NOT NULL,
  monto NUMERIC(12,2) NOT NULL,
  recibido NUMERIC(12,2),
  cambio NUMERIC(12,2),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT movimiento_pagos_metodo_check
    CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA')),
  CONSTRAINT movimiento_pagos_monto_check CHECK (monto >= 0 AND monto <= 9999999999.99),
  CONSTRAINT movimiento_pagos_efectivo_check CHECK (
    (
      metodo_pago = 'EFECTIVO'
      AND (recibido IS NULL OR recibido >= monto)
      AND (cambio IS NULL OR cambio >= 0)
    )
    OR (
      metodo_pago <> 'EFECTIVO'
      AND recibido IS NULL
      AND cambio IS NULL
    )
  ),
  CONSTRAINT movimiento_pagos_medio_unico_uq UNIQUE (movimiento_id, metodo_pago)
);

CREATE INDEX IF NOT EXISTS movimiento_pagos_movimiento_idx
  ON movimiento_pagos (movimiento_id);

-- Un movimiento de venta, cancelación o devolución existente recibe su medio único.
-- Las ventas en efectivo conservan el recibido y el cambio de la venta.
INSERT INTO movimiento_pagos (movimiento_id, metodo_pago, monto, recibido, cambio)
SELECT m.id,
       m.metodo_pago,
       m.monto,
       CASE WHEN m.tipo = 'VENTA' AND m.metodo_pago = 'EFECTIVO' THEN v.recibido END,
       CASE WHEN m.tipo = 'VENTA' AND m.metodo_pago = 'EFECTIVO' THEN v.cambio END
FROM movimientos m
LEFT JOIN ventas v ON v.id = m.venta_id
WHERE m.tipo IN ('VENTA', 'CANCELACION', 'DEVOLUCION')
  AND m.metodo_pago IS NOT NULL
ON CONFLICT (movimiento_id, metodo_pago) DO NOTHING;

CREATE OR REPLACE FUNCTION impedir_modificacion_movimiento_pagos()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  RAISE EXCEPTION 'Los medios de pago de un movimiento son inmutables.' USING ERRCODE = '55000';
END;
$$;

DROP TRIGGER IF EXISTS movimiento_pagos_inmutable_tr ON movimiento_pagos;
CREATE TRIGGER movimiento_pagos_inmutable_tr
  BEFORE UPDATE OR DELETE ON movimiento_pagos
  FOR EACH ROW EXECUTE FUNCTION impedir_modificacion_movimiento_pagos();

-- Una venta con más de un medio se marca como MIXTO. Los importes por medio
-- siempre se leen de movimiento_pagos.
ALTER TABLE ventas DROP CONSTRAINT IF EXISTS ventas_metodo_check;
ALTER TABLE ventas
  ADD CONSTRAINT ventas_metodo_check
    CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'MIXTO'));

ALTER TABLE movimientos DROP CONSTRAINT IF EXISTS movimientos_metodo_pago_check;
ALTER TABLE movimientos
  ADD CONSTRAINT movimientos_metodo_pago_check CHECK (
    (
      tipo IN ('VENTA', 'CANCELACION', 'DEVOLUCION')
      AND metodo_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'MIXTO')
    )
    OR
    (
      tipo IN ('APERTURA', 'RETIRO', 'INGRESO', 'CIERRE')
      AND metodo_pago IS NULL
    )
  );

-- Vista de consulta: cada medio de un movimiento es una fila con su importe.
-- Los demás movimientos (apertura, retiro, ingreso, cierre) conservan su monto
-- sin medio. Las agregaciones de caja y reportes leen de aquí.
CREATE OR REPLACE VIEW movimientos_por_medio AS
SELECT m.id AS movimiento_id,
       m.sesion_id,
       m.caja_id,
       m.usuario_id,
       m.tipo,
       m.creado_en,
       m.actor_inferido,
       mp.metodo_pago,
       mp.monto
FROM movimientos m
JOIN movimiento_pagos mp ON mp.movimiento_id = m.id
UNION ALL
SELECT m.id,
       m.sesion_id,
       m.caja_id,
       m.usuario_id,
       m.tipo,
       m.creado_en,
       m.actor_inferido,
       NULL::VARCHAR,
       m.monto
FROM movimientos m
WHERE m.tipo NOT IN ('VENTA', 'CANCELACION', 'DEVOLUCION');
