-- Protección append-only de documentos y partidas.
CREATE OR REPLACE FUNCTION proteger_orden_compra()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Las órdenes de compra son auditables y no pueden eliminarse.'
      USING ERRCODE = '55000';
  END IF;
  IF ROW(
    NEW.id, NEW.folio, NEW.proveedor_id, NEW.proveedor_nombre, NEW.referencia,
    NEW.notas, NEW.subtotal, NEW.iva, NEW.total, NEW.creado_por_usuario_id,
    NEW.creado_en
  ) IS DISTINCT FROM ROW(
    OLD.id, OLD.folio, OLD.proveedor_id, OLD.proveedor_nombre, OLD.referencia,
    OLD.notas, OLD.subtotal, OLD.iva, OLD.total, OLD.creado_por_usuario_id,
    OLD.creado_en
  ) THEN
    RAISE EXCEPTION 'El contenido comercial de una orden de compra es inmutable.'
      USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$function$;

