-- Proveedores y compras sobre la misma existencia física y kardex.
-- Los documentos se publican completos: sus partidas y movimientos son append-only.
-- Una orden PARCIAL puede cancelarse para cerrar el remanente; lo ya recibido
-- permanece en inventario y sólo sale mediante una devolución a proveedor.

CREATE TABLE proveedores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(160) NOT NULL,
  razon_social VARCHAR(180),
  rfc VARCHAR(20),
  contacto VARCHAR(120),
  telefono VARCHAR(30),
  email VARCHAR(254),
  direccion TEXT,
  notas TEXT,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_por_usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT proveedores_nombre_check CHECK (btrim(nombre) <> ''),
  CONSTRAINT proveedores_razon_social_check CHECK (
    razon_social IS NULL OR btrim(razon_social) <> ''
  ),
  CONSTRAINT proveedores_rfc_check CHECK (rfc IS NULL OR btrim(rfc) <> ''),
  CONSTRAINT proveedores_contacto_check CHECK (contacto IS NULL OR btrim(contacto) <> ''),
  CONSTRAINT proveedores_telefono_check CHECK (telefono IS NULL OR btrim(telefono) <> ''),
  CONSTRAINT proveedores_email_check CHECK (email IS NULL OR btrim(email) <> ''),
  CONSTRAINT proveedores_direccion_check CHECK (direccion IS NULL OR btrim(direccion) <> '')
);

CREATE UNIQUE INDEX proveedores_nombre_lower_uq ON proveedores (lower(nombre));
CREATE UNIQUE INDEX proveedores_rfc_lower_uq
  ON proveedores (lower(rfc)) WHERE rfc IS NOT NULL;
CREATE INDEX proveedores_activos_nombre_idx
  ON proveedores (nombre, id) WHERE activo;
CREATE INDEX proveedores_creado_por_idx ON proveedores (creado_por_usuario_id);

CREATE TRIGGER proveedores_actualizado_en_trg
  BEFORE UPDATE ON proveedores
  FOR EACH ROW EXECUTE FUNCTION marcar_actualizado_en();

CREATE SEQUENCE ordenes_compra_folio_seq START WITH 1;

CREATE TABLE ordenes_compra (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio VARCHAR(24) NOT NULL UNIQUE
    DEFAULT ('OC-' || LPAD(nextval('ordenes_compra_folio_seq')::text, 10, '0')),
  proveedor_id BIGINT NOT NULL REFERENCES proveedores(id) ON DELETE RESTRICT,
  proveedor_nombre VARCHAR(160) NOT NULL,
  estado VARCHAR(16) NOT NULL DEFAULT 'EMITIDA',
  referencia VARCHAR(100),
  notas TEXT,
  subtotal NUMERIC(12,2) NOT NULL,
  iva NUMERIC(12,2) NOT NULL,
  total NUMERIC(12,2) NOT NULL,
  creado_por_usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ordenes_compra_proveedor_nombre_check CHECK (btrim(proveedor_nombre) <> ''),
  CONSTRAINT ordenes_compra_estado_check CHECK (
    estado IN ('EMITIDA', 'PARCIAL', 'RECIBIDA', 'CANCELADA')
  ),
  CONSTRAINT ordenes_compra_referencia_check CHECK (
    referencia IS NULL OR btrim(referencia) <> ''
  ),
  CONSTRAINT ordenes_compra_subtotal_check CHECK (subtotal >= 0),
  CONSTRAINT ordenes_compra_iva_check CHECK (iva >= 0),
  CONSTRAINT ordenes_compra_total_check CHECK (
    total >= 0 AND total = ROUND(subtotal + iva, 2)
  ),
  CONSTRAINT ordenes_compra_id_proveedor_uq UNIQUE (id, proveedor_id)
);

CREATE INDEX ordenes_compra_proveedor_fecha_idx
  ON ordenes_compra (proveedor_id, creado_en DESC, id DESC);
CREATE INDEX ordenes_compra_estado_fecha_idx
  ON ordenes_compra (estado, creado_en DESC, id DESC);
CREATE INDEX ordenes_compra_usuario_fecha_idx
  ON ordenes_compra (creado_por_usuario_id, creado_en DESC, id DESC);

CREATE TRIGGER ordenes_compra_actualizado_en_trg
  BEFORE UPDATE ON ordenes_compra
  FOR EACH ROW EXECUTE FUNCTION marcar_actualizado_en();

CREATE TABLE detalle_ordenes_compra (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_compra_id BIGINT NOT NULL REFERENCES ordenes_compra(id) ON DELETE RESTRICT,
  producto_id INTEGER NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
  producto_sku VARCHAR(24) NOT NULL,
  producto_titulo VARCHAR(160) NOT NULL,
  cantidad INTEGER NOT NULL,
  costo_unitario NUMERIC(12,2) NOT NULL,
  iva_porcentaje NUMERIC(5,2) NOT NULL,
  subtotal NUMERIC(12,2) NOT NULL,
  iva NUMERIC(12,2) NOT NULL,
  total NUMERIC(12,2) NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT detalle_ordenes_compra_sku_check CHECK (btrim(producto_sku) <> ''),
  CONSTRAINT detalle_ordenes_compra_titulo_check CHECK (btrim(producto_titulo) <> ''),
  CONSTRAINT detalle_ordenes_compra_cantidad_check CHECK (cantidad > 0),
  CONSTRAINT detalle_ordenes_compra_costo_check CHECK (costo_unitario >= 0),
  CONSTRAINT detalle_ordenes_compra_iva_porcentaje_check
    CHECK (iva_porcentaje BETWEEN 0 AND 100),
  CONSTRAINT detalle_ordenes_compra_importes_check CHECK (
    subtotal = ROUND(costo_unitario * cantidad, 2)
    AND iva = ROUND(subtotal * iva_porcentaje / 100, 2)
    AND total = ROUND(subtotal + iva, 2)
  ),
  CONSTRAINT detalle_ordenes_compra_orden_producto_uq
    UNIQUE (orden_compra_id, producto_id),
  CONSTRAINT detalle_ordenes_compra_id_orden_producto_uq
    UNIQUE (id, orden_compra_id, producto_id)
);

CREATE INDEX detalle_ordenes_compra_producto_idx
  ON detalle_ordenes_compra (producto_id, orden_compra_id);

CREATE TABLE orden_compra_transiciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_compra_id BIGINT NOT NULL REFERENCES ordenes_compra(id) ON DELETE RESTRICT,
  estado_anterior VARCHAR(16),
  estado_nuevo VARCHAR(16) NOT NULL,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  motivo VARCHAR(240) NOT NULL,
  origen_clave VARCHAR(180) NOT NULL UNIQUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT orden_compra_transiciones_anterior_check CHECK (
    estado_anterior IS NULL
    OR estado_anterior IN ('EMITIDA', 'PARCIAL', 'RECIBIDA', 'CANCELADA')
  ),
  CONSTRAINT orden_compra_transiciones_nuevo_check CHECK (
    estado_nuevo IN ('EMITIDA', 'PARCIAL', 'RECIBIDA', 'CANCELADA')
  ),
  CONSTRAINT orden_compra_transiciones_cambio_check CHECK (
    (estado_anterior IS NULL AND estado_nuevo = 'EMITIDA')
    OR (estado_anterior IS NOT NULL AND estado_anterior <> estado_nuevo)
  ),
  CONSTRAINT orden_compra_transiciones_motivo_check CHECK (btrim(motivo) <> ''),
  CONSTRAINT orden_compra_transiciones_origen_check CHECK (btrim(origen_clave) <> '')
);

CREATE INDEX orden_compra_transiciones_orden_idx
  ON orden_compra_transiciones (orden_compra_id, id DESC);

