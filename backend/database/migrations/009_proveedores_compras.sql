      AND venta_id IS NULL AND cancelacion_id IS NULL AND devolucion_id IS NULL
      AND pedido_id IS NULL AND reserva_id IS NULL
      AND recepcion_compra_id IS NULL AND detalle_recepcion_compra_id IS NULL
      AND devolucion_proveedor_id IS NOT NULL AND detalle_devolucion_proveedor_id IS NOT NULL
      AND delta_fisico < 0 AND delta_reservado = 0
