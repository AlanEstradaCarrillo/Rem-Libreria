-- Conciliación diferida de orden, recepciones, devoluciones y kardex.
CREATE OR REPLACE FUNCTION validar_orden_compra_conciliada(p_orden_id BIGINT)
RETURNS VOID LANGUAGE plpgsql AS $function$
DECLARE
  v_orden ordenes_compra%ROWTYPE;
  v_lineas BIGINT;
  v_subtotal NUMERIC(12,2);
  v_iva NUMERIC(12,2);
  v_total NUMERIC(12,2);
  v_recibido BIGINT;
  v_ultimo_estado VARCHAR(16);
  v_hay_remanente BOOLEAN;
BEGIN
  IF p_orden_id IS NULL THEN RETURN; END IF;
  SELECT * INTO v_orden FROM ordenes_compra WHERE id = p_orden_id;
  IF NOT FOUND THEN RETURN; END IF;

  SELECT COUNT(*), ROUND(COALESCE(SUM(subtotal), 0), 2),
         ROUND(COALESCE(SUM(iva), 0), 2), ROUND(COALESCE(SUM(total), 0), 2)
  INTO v_lineas, v_subtotal, v_iva, v_total
  FROM detalle_ordenes_compra WHERE orden_compra_id = p_orden_id;
  IF v_lineas = 0 THEN
    RAISE EXCEPTION 'La orden de compra % no contiene partidas.', p_orden_id
      USING ERRCODE = '23514';
  END IF;
  IF v_subtotal <> v_orden.subtotal OR v_iva <> v_orden.iva OR v_total <> v_orden.total THEN
    RAISE EXCEPTION 'Los totales de la orden de compra % no concilian.', p_orden_id
      USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM detalle_ordenes_compra d
    LEFT JOIN (
      SELECT detalle_orden_compra_id, SUM(cantidad)::BIGINT AS cantidad
      FROM detalle_recepciones_compra GROUP BY detalle_orden_compra_id
    ) r ON r.detalle_orden_compra_id = d.id
    WHERE d.orden_compra_id = p_orden_id
      AND COALESCE(r.cantidad, 0) > d.cantidad
  ) THEN
    RAISE EXCEPTION 'La orden de compra % tiene cantidades recibidas en exceso.', p_orden_id
      USING ERRCODE = '23514';
  END IF;

  SELECT COALESCE(SUM(r.cantidad), 0)::BIGINT,
         COALESCE(BOOL_OR(COALESCE(r.cantidad, 0) < d.cantidad), FALSE)
  INTO v_recibido, v_hay_remanente
  FROM detalle_ordenes_compra d
  LEFT JOIN (
    SELECT detalle_orden_compra_id, SUM(cantidad)::BIGINT AS cantidad
    FROM detalle_recepciones_compra GROUP BY detalle_orden_compra_id
  ) r ON r.detalle_orden_compra_id = d.id
  WHERE d.orden_compra_id = p_orden_id;

  IF v_orden.estado = 'EMITIDA' AND v_recibido <> 0 THEN
    RAISE EXCEPTION 'Una orden EMITIDA no puede tener recepciones.' USING ERRCODE = '23514';
  ELSIF v_orden.estado = 'PARCIAL' AND (v_recibido = 0 OR NOT v_hay_remanente) THEN
    RAISE EXCEPTION 'El estado PARCIAL no corresponde a las recepciones.' USING ERRCODE = '23514';
  ELSIF v_orden.estado = 'RECIBIDA' AND (v_recibido = 0 OR v_hay_remanente) THEN
    RAISE EXCEPTION 'El estado RECIBIDA no corresponde a las recepciones.' USING ERRCODE = '23514';
  ELSIF v_orden.estado = 'CANCELADA' AND NOT v_hay_remanente THEN
    RAISE EXCEPTION 'Una orden totalmente recibida no puede cancelarse.' USING ERRCODE = '23514';
  END IF;

  SELECT estado_nuevo INTO v_ultimo_estado
  FROM orden_compra_transiciones
  WHERE orden_compra_id = p_orden_id ORDER BY id DESC LIMIT 1;
  IF v_ultimo_estado IS DISTINCT FROM v_orden.estado THEN
    RAISE EXCEPTION 'El historial de la orden % no concilia con su estado.', p_orden_id
      USING ERRCODE = '23514';
  END IF;
END
$function$;

CREATE OR REPLACE FUNCTION validar_recepcion_compra_conciliada(p_recepcion_id BIGINT)
RETURNS VOID LANGUAGE plpgsql AS $function$
DECLARE
  v_recepcion recepciones_compra%ROWTYPE;
  v_lineas BIGINT;
  v_subtotal NUMERIC(12,2);
  v_iva NUMERIC(12,2);
  v_total NUMERIC(12,2);
BEGIN
  IF p_recepcion_id IS NULL THEN RETURN; END IF;
  SELECT * INTO v_recepcion FROM recepciones_compra WHERE id = p_recepcion_id;
  IF NOT FOUND THEN RETURN; END IF;

  SELECT COUNT(*), ROUND(COALESCE(SUM(subtotal), 0), 2),
         ROUND(COALESCE(SUM(iva), 0), 2), ROUND(COALESCE(SUM(total), 0), 2)
  INTO v_lineas, v_subtotal, v_iva, v_total
  FROM detalle_recepciones_compra WHERE recepcion_compra_id = p_recepcion_id;
  IF v_lineas = 0 THEN
    RAISE EXCEPTION 'La recepción % no contiene partidas.', p_recepcion_id
      USING ERRCODE = '23514';
  END IF;
  IF v_subtotal <> v_recepcion.subtotal OR v_iva <> v_recepcion.iva
     OR v_total <> v_recepcion.total THEN
    RAISE EXCEPTION 'Los totales de la recepción % no concilian.', p_recepcion_id
      USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM detalle_recepciones_compra d
    LEFT JOIN inventario_movimientos im
      ON im.detalle_recepcion_compra_id = d.id AND im.tipo = 'RECEPCION_COMPRA'
    WHERE d.recepcion_compra_id = p_recepcion_id
      AND (
        im.id IS NULL OR im.recepcion_compra_id <> d.recepcion_compra_id
        OR im.producto_id <> d.producto_id OR im.delta_fisico <> d.cantidad
        OR im.delta_reservado <> 0 OR im.actor <> 'USUARIO'
        OR im.usuario_id <> v_recepcion.recibido_por_usuario_id
      )
  ) THEN
    RAISE EXCEPTION 'La recepción % no concilia con el kardex.', p_recepcion_id
      USING ERRCODE = '23514';
  END IF;
  PERFORM validar_orden_compra_conciliada(v_recepcion.orden_compra_id);
END
$function$;

CREATE OR REPLACE FUNCTION validar_devolucion_proveedor_conciliada(p_devolucion_id BIGINT)
RETURNS VOID LANGUAGE plpgsql AS $function$
DECLARE
  v_devolucion devoluciones_proveedor%ROWTYPE;
  v_lineas BIGINT;
  v_subtotal NUMERIC(12,2);
  v_iva NUMERIC(12,2);
  v_total NUMERIC(12,2);
BEGIN
  IF p_devolucion_id IS NULL THEN RETURN; END IF;
  SELECT * INTO v_devolucion FROM devoluciones_proveedor WHERE id = p_devolucion_id;
  IF NOT FOUND THEN RETURN; END IF;

  SELECT COUNT(*), ROUND(COALESCE(SUM(subtotal), 0), 2),
         ROUND(COALESCE(SUM(iva), 0), 2), ROUND(COALESCE(SUM(total), 0), 2)
  INTO v_lineas, v_subtotal, v_iva, v_total
  FROM detalle_devoluciones_proveedor WHERE devolucion_proveedor_id = p_devolucion_id;
  IF v_lineas = 0 THEN
    RAISE EXCEPTION 'La devolución a proveedor % no contiene partidas.', p_devolucion_id
      USING ERRCODE = '23514';
  END IF;
  IF v_subtotal <> v_devolucion.subtotal OR v_iva <> v_devolucion.iva
     OR v_total <> v_devolucion.total THEN
    RAISE EXCEPTION 'Los totales de la devolución % no concilian.', p_devolucion_id
      USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM detalle_devoluciones_proveedor d
    JOIN detalle_recepciones_compra r ON r.id = d.detalle_recepcion_compra_id
    WHERE d.devolucion_proveedor_id = p_devolucion_id
      AND (d.costo_unitario <> r.costo_unitario OR d.iva_porcentaje <> r.iva_porcentaje)
  ) THEN
    RAISE EXCEPTION 'La devolución % alteró el costo o IVA recibido.', p_devolucion_id
      USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM detalle_recepciones_compra r
    JOIN (
      SELECT detalle_recepcion_compra_id, SUM(cantidad)::BIGINT AS cantidad
      FROM detalle_devoluciones_proveedor GROUP BY detalle_recepcion_compra_id
    ) d ON d.detalle_recepcion_compra_id = r.id
    WHERE d.cantidad > r.cantidad
  ) THEN
    RAISE EXCEPTION 'La devolución % excede la cantidad recibida.', p_devolucion_id
      USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM detalle_devoluciones_proveedor d
    LEFT JOIN inventario_movimientos im
      ON im.detalle_devolucion_proveedor_id = d.id
      AND im.tipo = 'DEVOLUCION_PROVEEDOR'
    WHERE d.devolucion_proveedor_id = p_devolucion_id
      AND (
        im.id IS NULL OR im.devolucion_proveedor_id <> d.devolucion_proveedor_id
        OR im.producto_id <> d.producto_id OR im.delta_fisico <> -d.cantidad
        OR im.delta_reservado <> 0 OR im.actor <> 'USUARIO'
        OR im.usuario_id <> v_devolucion.creado_por_usuario_id
      )
  ) THEN
    RAISE EXCEPTION 'La devolución % no concilia con el kardex.', p_devolucion_id
      USING ERRCODE = '23514';
  END IF;
END
$function$;

