-- Último costo realmente recibido. El detalle inmutable conserva la evidencia.
CREATE OR REPLACE FUNCTION aplicar_ultimo_costo_recibido()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
DECLARE
  v_costo_actual NUMERIC(12,2);
BEGIN
  SELECT costo INTO v_costo_actual
  FROM productos WHERE id = NEW.producto_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Producto % no encontrado.', NEW.producto_id USING ERRCODE = '23503';
  END IF;
  IF NEW.costo_anterior <> v_costo_actual THEN
    RAISE EXCEPTION 'El costo anterior de producto % cambió concurrentemente.', NEW.producto_id
      USING ERRCODE = '40001';
  END IF;
  UPDATE productos
  SET costo = NEW.costo_nuevo, actualizado_en = NOW()
  WHERE id = NEW.producto_id;
  RETURN NEW;
END
$function$;

CREATE TRIGGER detalle_recepciones_compra_aplicar_costo_trg
  BEFORE INSERT ON detalle_recepciones_compra
  FOR EACH ROW EXECUTE FUNCTION aplicar_ultimo_costo_recibido();

-- Historial de estados append-only.
CREATE OR REPLACE FUNCTION validar_insert_transicion_orden_compra()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
DECLARE
  v_estado VARCHAR(16);
BEGIN
  SELECT estado INTO v_estado FROM ordenes_compra
  WHERE id = NEW.orden_compra_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Orden de compra % no encontrada.', NEW.orden_compra_id
      USING ERRCODE = '23503';
  END IF;

  IF NEW.estado_anterior IS NULL THEN
    IF v_estado <> 'EMITIDA' OR NEW.estado_nuevo <> 'EMITIDA'
       OR EXISTS (
         SELECT 1 FROM orden_compra_transiciones
         WHERE orden_compra_id = NEW.orden_compra_id
       ) THEN
      RAISE EXCEPTION 'Transición inicial de orden de compra inválida.'
        USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
  END IF;

  IF v_estado <> NEW.estado_anterior THEN
    RAISE EXCEPTION 'La orden está en %, no en %.', v_estado, NEW.estado_anterior
      USING ERRCODE = '40001';
  END IF;
  IF NOT (
    (NEW.estado_anterior = 'EMITIDA'
      AND NEW.estado_nuevo IN ('PARCIAL', 'RECIBIDA', 'CANCELADA'))
    OR (NEW.estado_anterior = 'PARCIAL'
      AND NEW.estado_nuevo IN ('RECIBIDA', 'CANCELADA'))
  ) THEN
    RAISE EXCEPTION 'Transición de orden no permitida: % -> %.',
      NEW.estado_anterior, NEW.estado_nuevo USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$function$;

CREATE TRIGGER orden_compra_transiciones_validar_trg
  BEFORE INSERT ON orden_compra_transiciones
  FOR EACH ROW EXECUTE FUNCTION validar_insert_transicion_orden_compra();

CREATE OR REPLACE FUNCTION aplicar_transicion_orden_compra()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
DECLARE
  v_actualizados INTEGER;
BEGIN
  IF NEW.estado_anterior IS NULL THEN RETURN NULL; END IF;
  PERFORM set_config('libra.aplicando_transicion_orden_compra', '1', TRUE);
  UPDATE ordenes_compra SET estado = NEW.estado_nuevo
  WHERE id = NEW.orden_compra_id AND estado = NEW.estado_anterior;
  GET DIAGNOSTICS v_actualizados = ROW_COUNT;
  PERFORM set_config('libra.aplicando_transicion_orden_compra', '0', TRUE);
  IF v_actualizados <> 1 THEN
    RAISE EXCEPTION 'La orden de compra cambió concurrentemente.' USING ERRCODE = '40001';
  END IF;
  RETURN NULL;
END
$function$;

CREATE TRIGGER orden_compra_transiciones_aplicar_trg
  AFTER INSERT ON orden_compra_transiciones
  FOR EACH ROW EXECUTE FUNCTION aplicar_transicion_orden_compra();

