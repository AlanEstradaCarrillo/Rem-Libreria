-- Las partidas sólo pueden armarse en la misma transacción que su cabecera.
CREATE OR REPLACE FUNCTION validar_armado_documento_compra()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
DECLARE
  v_creado_en TIMESTAMPTZ;
BEGIN
  IF TG_TABLE_NAME = 'detalle_ordenes_compra' THEN
    SELECT creado_en INTO v_creado_en
    FROM ordenes_compra WHERE id = NEW.orden_compra_id FOR KEY SHARE;
  ELSIF TG_TABLE_NAME = 'detalle_recepciones_compra' THEN
    SELECT creado_en INTO v_creado_en
    FROM recepciones_compra WHERE id = NEW.recepcion_compra_id FOR KEY SHARE;
  ELSE
    SELECT creado_en INTO v_creado_en
    FROM devoluciones_proveedor WHERE id = NEW.devolucion_proveedor_id FOR KEY SHARE;
  END IF;

  IF NOT FOUND OR v_creado_en <> transaction_timestamp() THEN
    RAISE EXCEPTION 'Las partidas sólo se crean junto con su documento.'
      USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$function$;

