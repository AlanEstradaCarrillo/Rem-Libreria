-- Núcleo editorial: obras/manuscritos, colaboradores, ediciones vinculadas,
-- contratos, derechos y flujos auditables.
--
-- productos continúa siendo la única edición vendible y la fuente común de
-- precio, inventario, POS y tienda. Las obras sólo agrupan productos existentes.

CREATE SEQUENCE obras_editoriales_folio_seq START WITH 1;
CREATE SEQUENCE contratos_editoriales_folio_seq START WITH 1;

