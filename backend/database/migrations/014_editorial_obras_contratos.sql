LANGUAGE plpgsql
AS $function$
DECLARE
  v_estado VARCHAR(16);
  v_ultimo VARCHAR(16);
BEGIN
  SELECT estado INTO v_estado FROM obras_editoriales WHERE id = p_obra_id;
  IF NOT FOUND THEN RETURN; END IF;
  SELECT estado_nuevo INTO v_ultimo
  FROM obra_editorial_transiciones
  WHERE obra_editorial_id = p_obra_id ORDER BY id DESC LIMIT 1;
  IF v_ultimo IS DISTINCT FROM v_estado THEN
    RAISE EXCEPTION 'El historial de la obra % no coincide con su estado.', p_obra_id
      USING ERRCODE = '23514';
  END IF;
END
$function$;

CREATE OR REPLACE FUNCTION validar_contrato_editorial_conciliado(p_contrato_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $function$
DECLARE
  v_estado VARCHAR(12);
  v_ultimo VARCHAR(12);
BEGIN
  SELECT estado INTO v_estado FROM contratos_editoriales WHERE id = p_contrato_id;
  IF NOT FOUND THEN RETURN; END IF;
  SELECT estado_nuevo INTO v_ultimo
  FROM contrato_editorial_transiciones
  WHERE contrato_editorial_id = p_contrato_id ORDER BY id DESC LIMIT 1;
  IF v_ultimo IS DISTINCT FROM v_estado THEN
    RAISE EXCEPTION 'El historial del contrato % no coincide con su estado.', p_contrato_id
