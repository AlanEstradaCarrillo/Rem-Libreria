  BEFORE DELETE OR UPDATE OF obra_editorial_id, colaborador_editorial_id
  ON obra_editorial_colaboradores
  FOR EACH ROW EXECUTE FUNCTION proteger_vinculo_con_contrato_editorial();

CREATE OR REPLACE FUNCTION proteger_obra_editorial()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Las obras editoriales no se eliminan; deben archivarse.'
      USING ERRCODE = '55000';
  END IF;
  IF NEW.id <> OLD.id OR NEW.folio <> OLD.folio
     OR NEW.creado_por_usuario_id <> OLD.creado_por_usuario_id
     OR NEW.creado_en <> OLD.creado_en THEN
    RAISE EXCEPTION 'No se puede modificar la identidad de la obra editorial.'
      USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$function$;

CREATE TRIGGER obras_editoriales_proteger_trg
  BEFORE UPDATE OR DELETE ON obras_editoriales
  FOR EACH ROW EXECUTE FUNCTION proteger_obra_editorial();

CREATE OR REPLACE FUNCTION proteger_contrato_editorial()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Los contratos editoriales no se eliminan; deben terminarse.'
      USING ERRCODE = '55000';
  END IF;
  IF NEW.id <> OLD.id OR NEW.folio <> OLD.folio
     OR NEW.obra_folio <> OLD.obra_folio
     OR NEW.obra_titulo <> OLD.obra_titulo
     OR NEW.colaborador_nombre <> OLD.colaborador_nombre
     OR NEW.creado_por_usuario_id <> OLD.creado_por_usuario_id
     OR NEW.creado_en <> OLD.creado_en THEN
    RAISE EXCEPTION 'No se puede modificar la identidad o snapshots del contrato.'
      USING ERRCODE = '55000';
  END IF;
  IF OLD.estado <> 'BORRADOR' AND (
    NEW.obra_editorial_id <> OLD.obra_editorial_id
    OR NEW.colaborador_editorial_id <> OLD.colaborador_editorial_id
    OR NEW.tipo <> OLD.tipo OR NEW.derechos <> OLD.derechos
    OR NEW.territorio <> OLD.territorio
    OR NEW.idioma_derechos <> OLD.idioma_derechos
    OR NEW.exclusividad <> OLD.exclusividad
    OR NEW.vigente_desde <> OLD.vigente_desde
    OR NEW.vigente_hasta IS DISTINCT FROM OLD.vigente_hasta
    OR NEW.base_regalia <> OLD.base_regalia
    OR NEW.porcentaje_regalia <> OLD.porcentaje_regalia
    OR NEW.anticipo <> OLD.anticipo OR NEW.moneda <> OLD.moneda
    OR NEW.periodicidad_liquidacion <> OLD.periodicidad_liquidacion
    OR NEW.notas IS DISTINCT FROM OLD.notas
  ) THEN
    RAISE EXCEPTION 'Los términos de un contrato activado son inmutables.'
      USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$function$;

CREATE TRIGGER contratos_editoriales_proteger_trg
  BEFORE UPDATE OR DELETE ON contratos_editoriales
  FOR EACH ROW EXECUTE FUNCTION proteger_contrato_editorial();

CREATE OR REPLACE FUNCTION validar_producto_obra_historial_previo()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
  v_actual BIGINT;
  v_ultimo BIGINT;
  v_tiene_historial BOOLEAN;
BEGIN
  SELECT obra_editorial_id INTO v_actual
  FROM productos WHERE id = NEW.producto_id FOR KEY SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Producto editorial no encontrado.' USING ERRCODE = '23503';
  END IF;
  IF v_actual IS DISTINCT FROM NEW.obra_anterior_id THEN
    RAISE EXCEPTION 'El vínculo anterior del producto cambió.' USING ERRCODE = '23514';
  END IF;

  SELECT TRUE, obra_nueva_id INTO v_tiene_historial, v_ultimo
  FROM producto_obra_editorial_historial
  WHERE producto_id = NEW.producto_id
  ORDER BY id DESC LIMIT 1;
  IF COALESCE(v_tiene_historial, FALSE)
     AND v_ultimo IS DISTINCT FROM NEW.obra_anterior_id THEN
    RAISE EXCEPTION 'El historial del vínculo editorial no es continuo.'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$function$;

CREATE TRIGGER producto_obra_editorial_historial_previo_trg
  BEFORE INSERT ON producto_obra_editorial_historial
  FOR EACH ROW EXECUTE FUNCTION validar_producto_obra_historial_previo();

