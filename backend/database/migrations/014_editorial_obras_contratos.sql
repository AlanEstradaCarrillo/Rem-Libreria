CREATE TABLE obras_editoriales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio VARCHAR(24) NOT NULL UNIQUE
    DEFAULT ('OBR-' || LPAD(nextval('obras_editoriales_folio_seq')::text, 10, '0')),
  titulo VARCHAR(240) NOT NULL,
  subtitulo VARCHAR(240),
  sinopsis TEXT,
  idioma VARCHAR(60) NOT NULL DEFAULT 'Español',
  estado VARCHAR(16) NOT NULL DEFAULT 'PROPUESTA',
  fecha_recepcion DATE NOT NULL DEFAULT CURRENT_DATE,
  fecha_objetivo_publicacion DATE,
  editor_responsable_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  notas TEXT,
  creado_por_usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT obras_editoriales_titulo_check CHECK (btrim(titulo) <> ''),
  CONSTRAINT obras_editoriales_subtitulo_check CHECK (
    subtitulo IS NULL OR btrim(subtitulo) <> ''
  ),
  CONSTRAINT obras_editoriales_sinopsis_check CHECK (
    sinopsis IS NULL OR btrim(sinopsis) <> ''
  ),
  CONSTRAINT obras_editoriales_idioma_check CHECK (btrim(idioma) <> ''),
