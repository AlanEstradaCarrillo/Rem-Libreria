  END IF;
END
$function$;

CREATE OR REPLACE FUNCTION validar_producto_obra_conciliado(p_producto_id INTEGER)
RETURNS VOID
LANGUAGE plpgsql
AS $function$
DECLARE
  v_obra BIGINT;
  v_ultima_obra BIGINT;
  v_tiene_historial BOOLEAN;
BEGIN
  SELECT obra_editorial_id INTO v_obra FROM productos WHERE id = p_producto_id;
  IF NOT FOUND THEN RETURN; END IF;
  SELECT TRUE, obra_nueva_id INTO v_tiene_historial, v_ultima_obra
  FROM producto_obra_editorial_historial
  WHERE producto_id = p_producto_id ORDER BY id DESC LIMIT 1;
  IF COALESCE(v_tiene_historial, FALSE) THEN
    IF v_ultima_obra IS DISTINCT FROM v_obra THEN
      RAISE EXCEPTION 'El historial editorial del producto % no coincide.', p_producto_id
        USING ERRCODE = '23514';
    END IF;
  ELSIF v_obra IS NOT NULL THEN
    RAISE EXCEPTION 'El producto % carece de historial editorial.', p_producto_id
      USING ERRCODE = '23514';
  END IF;
END
$function$;

CREATE OR REPLACE FUNCTION validar_editorial_conciliado_trg()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  IF TG_TABLE_NAME = 'obras_editoriales' THEN
    PERFORM validar_obra_editorial_conciliada(CASE WHEN TG_OP='DELETE' THEN OLD.id ELSE NEW.id END);
  ELSIF TG_TABLE_NAME = 'obra_editorial_transiciones' THEN
    PERFORM validar_obra_editorial_conciliada(
      CASE WHEN TG_OP='DELETE' THEN OLD.obra_editorial_id ELSE NEW.obra_editorial_id END
    );
  ELSIF TG_TABLE_NAME = 'contratos_editoriales' THEN
    PERFORM validar_contrato_editorial_conciliado(CASE WHEN TG_OP='DELETE' THEN OLD.id ELSE NEW.id END);
  ELSIF TG_TABLE_NAME = 'contrato_editorial_transiciones' THEN
    PERFORM validar_contrato_editorial_conciliado(
      CASE WHEN TG_OP='DELETE' THEN OLD.contrato_editorial_id ELSE NEW.contrato_editorial_id END
    );
  ELSIF TG_TABLE_NAME = 'productos' THEN
    PERFORM validar_producto_obra_conciliado(CASE WHEN TG_OP='DELETE' THEN OLD.id ELSE NEW.id END);
  ELSE
    PERFORM validar_producto_obra_conciliado(
      CASE WHEN TG_OP='DELETE' THEN OLD.producto_id ELSE NEW.producto_id END
    );
  END IF;
  RETURN NULL;
END
$function$;

CREATE CONSTRAINT TRIGGER obras_editoriales_conciliacion_trg
  AFTER INSERT OR UPDATE ON obras_editoriales DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_editorial_conciliado_trg();
CREATE CONSTRAINT TRIGGER obra_editorial_transiciones_conciliacion_trg
  AFTER INSERT ON obra_editorial_transiciones DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_editorial_conciliado_trg();
CREATE CONSTRAINT TRIGGER contratos_editoriales_conciliacion_trg
  AFTER INSERT OR UPDATE ON contratos_editoriales DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_editorial_conciliado_trg();
CREATE CONSTRAINT TRIGGER contrato_editorial_transiciones_conciliacion_trg
  AFTER INSERT ON contrato_editorial_transiciones DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_editorial_conciliado_trg();
CREATE CONSTRAINT TRIGGER productos_obra_editorial_conciliacion_trg
  AFTER UPDATE OF obra_editorial_id ON productos DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_editorial_conciliado_trg();
CREATE CONSTRAINT TRIGGER producto_obra_historial_conciliacion_trg
  AFTER INSERT ON producto_obra_editorial_historial DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_editorial_conciliado_trg();

