CREATE TABLE obra_editorial_transiciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  obra_editorial_id BIGINT NOT NULL REFERENCES obras_editoriales(id) ON DELETE RESTRICT,
  estado_anterior VARCHAR(16),
  estado_nuevo VARCHAR(16) NOT NULL,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  motivo VARCHAR(500) NOT NULL,
  origen_clave VARCHAR(180) NOT NULL UNIQUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT obra_editorial_transiciones_anterior_check CHECK (
    estado_anterior IS NULL OR estado_anterior IN (
      'PROPUESTA', 'EVALUACION', 'CONTRATADA', 'EDICION',
      'DISENO', 'IMPRESION', 'PUBLICADA', 'ARCHIVADA'
    )
  ),
  CONSTRAINT obra_editorial_transiciones_nuevo_check CHECK (
    estado_nuevo IN (
      'PROPUESTA', 'EVALUACION', 'CONTRATADA', 'EDICION',
      'DISENO', 'IMPRESION', 'PUBLICADA', 'ARCHIVADA'
    )
  ),
  CONSTRAINT obra_editorial_transiciones_cambio_check CHECK (
    (estado_anterior IS NULL AND estado_nuevo = 'PROPUESTA')
    OR (estado_anterior = 'PROPUESTA' AND estado_nuevo IN ('EVALUACION', 'ARCHIVADA'))
    OR (estado_anterior = 'EVALUACION' AND estado_nuevo IN ('PROPUESTA', 'CONTRATADA', 'ARCHIVADA'))
    OR (estado_anterior = 'CONTRATADA' AND estado_nuevo IN ('EVALUACION', 'EDICION', 'ARCHIVADA'))
    OR (estado_anterior = 'EDICION' AND estado_nuevo IN ('CONTRATADA', 'DISENO', 'ARCHIVADA'))
    OR (estado_anterior = 'DISENO' AND estado_nuevo IN ('EDICION', 'IMPRESION', 'ARCHIVADA'))
    OR (estado_anterior = 'IMPRESION' AND estado_nuevo IN ('DISENO', 'PUBLICADA', 'ARCHIVADA'))
    OR (estado_anterior = 'PUBLICADA' AND estado_nuevo = 'ARCHIVADA')
  ),
  CONSTRAINT obra_editorial_transiciones_motivo_check CHECK (btrim(motivo) <> ''),
  CONSTRAINT obra_editorial_transiciones_origen_check CHECK (btrim(origen_clave) <> '')
);

