CREATE OR REPLACE FUNCTION validar_cadena_transicion_editorial()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
  v_ultimo_estado TEXT;
BEGIN
  IF TG_TABLE_NAME = 'obra_editorial_transiciones' THEN
    SELECT estado_nuevo INTO v_ultimo_estado
    FROM obra_editorial_transiciones
    WHERE obra_editorial_id = NEW.obra_editorial_id
    ORDER BY id DESC LIMIT 1;
  ELSE
    SELECT estado_nuevo INTO v_ultimo_estado
    FROM contrato_editorial_transiciones
    WHERE contrato_editorial_id = NEW.contrato_editorial_id
    ORDER BY id DESC LIMIT 1;
  END IF;

  IF NEW.estado_anterior IS DISTINCT FROM v_ultimo_estado THEN
    RAISE EXCEPTION 'La transición editorial no continúa el historial vigente.'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$function$;

CREATE TRIGGER obra_editorial_transiciones_cadena_trg
  BEFORE INSERT ON obra_editorial_transiciones
  FOR EACH ROW EXECUTE FUNCTION validar_cadena_transicion_editorial();
CREATE TRIGGER contrato_editorial_transiciones_cadena_trg
  BEFORE INSERT ON contrato_editorial_transiciones
  FOR EACH ROW EXECUTE FUNCTION validar_cadena_transicion_editorial();

CREATE OR REPLACE FUNCTION validar_contrato_colaborador_obra()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM obra_editorial_colaboradores oc
    WHERE oc.obra_editorial_id = NEW.obra_editorial_id
      AND oc.colaborador_editorial_id = NEW.colaborador_editorial_id
  ) THEN
    RAISE EXCEPTION 'El colaborador debe pertenecer al equipo de la obra.'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$function$;

