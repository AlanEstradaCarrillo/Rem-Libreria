CREATE OR REPLACE FUNCTION proteger_vinculo_con_contrato_editorial()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  IF EXISTS (
    SELECT 1 FROM contratos_editoriales c
    WHERE c.obra_editorial_id = OLD.obra_editorial_id
      AND c.colaborador_editorial_id = OLD.colaborador_editorial_id
      AND c.estado <> 'TERMINADO'
  ) THEN
    RAISE EXCEPTION 'El vínculo pertenece a un contrato editorial no terminado.'
      USING ERRCODE = '55000';
  END IF;
  RETURN OLD;
END
$function$;

