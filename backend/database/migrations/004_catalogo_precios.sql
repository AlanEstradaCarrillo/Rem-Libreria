ALTER TABLE categorias
  ADD COLUMN IF NOT EXISTS slug VARCHAR(120),
  ADD COLUMN IF NOT EXISTS descripcion TEXT,
  ADD COLUMN IF NOT EXISTS activo BOOLEAN NOT NULL DEFAULT TRUE,
  ADD COLUMN IF NOT EXISTS orden INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW();

UPDATE categorias
SET slug = 'categoria-' || id::text
WHERE slug IS NULL OR btrim(slug) = '';

DO $migration$
BEGIN
  IF EXISTS (
    SELECT lower(nombre)
    FROM categorias
    GROUP BY lower(nombre)
    HAVING COUNT(*) > 1
  ) THEN
    RAISE EXCEPTION 'Hay categorías duplicadas ignorando mayúsculas; deben resolverse antes de migrar.';
  END IF;
END
$migration$;

CREATE OR REPLACE FUNCTION completar_slug_categoria()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  IF NEW.slug IS NULL OR btrim(NEW.slug) = '' THEN
    NEW.slug := 'categoria-' || NEW.id::text;
  END IF;
  RETURN NEW;
END
$function$;

