CREATE TABLE consignaciones_editoriales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio VARCHAR(24) NOT NULL UNIQUE
    DEFAULT ('CON-' || LPAD(nextval('consignaciones_editoriales_folio_seq')::text, 10, '0')),
  cliente_id BIGINT NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
  cliente_nombre VARCHAR(120) NOT NULL,
  cliente_telefono VARCHAR(30),
  cliente_email VARCHAR(254),
  cliente_direccion TEXT,
  tipo_comercial VARCHAR(16) NOT NULL,
  segmento_precio VARCHAR(10) NOT NULL,
  fecha_envio_programada DATE NOT NULL,
  fecha_limite DATE,
  moneda CHAR(3) NOT NULL DEFAULT 'MXN',
  referencia VARCHAR(120),
  notas TEXT,
  estado VARCHAR(12) NOT NULL DEFAULT 'BORRADOR',
  creado_por_usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  enviado_por_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  enviado_en TIMESTAMPTZ,
  cerrado_por_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  cerrado_en TIMESTAMPTZ,
  cancelado_por_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  cancelado_en TIMESTAMPTZ,
  cancelacion_motivo VARCHAR(500),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT consignaciones_cliente_snapshot_check CHECK (
    btrim(cliente_nombre) <> ''
    AND (cliente_telefono IS NULL OR btrim(cliente_telefono) <> '')
    AND (cliente_email IS NULL OR btrim(cliente_email) <> '')
    AND (cliente_direccion IS NULL OR btrim(cliente_direccion) <> '')
  ),
  CONSTRAINT consignaciones_tipo_comercial_check CHECK (
    tipo_comercial IN ('LIBRERIA', 'DISTRIBUIDOR', 'INSTITUCION')
  ),
  CONSTRAINT consignaciones_segmento_check CHECK (segmento_precio = 'MAYOREO'),
  CONSTRAINT consignaciones_fecha_check CHECK (
    fecha_limite IS NULL OR fecha_limite >= fecha_envio_programada
  ),
  CONSTRAINT consignaciones_moneda_check CHECK (moneda ~ '^[A-Z]{3}$'),
  CONSTRAINT consignaciones_referencia_check CHECK (
    referencia IS NULL OR btrim(referencia) <> ''
  ),
  CONSTRAINT consignaciones_notas_check CHECK (notas IS NULL OR btrim(notas) <> ''),
  CONSTRAINT consignaciones_estado_check CHECK (
    estado IN ('BORRADOR', 'ENVIADA', 'PARCIAL', 'LIQUIDADA', 'CERRADA', 'CANCELADA')
  ),
  CONSTRAINT consignaciones_cancelacion_motivo_check CHECK (
    cancelacion_motivo IS NULL OR btrim(cancelacion_motivo) <> ''
  ),
  CONSTRAINT consignaciones_efectos_estado_check CHECK (
    (
      estado = 'BORRADOR'
      AND enviado_por_usuario_id IS NULL AND enviado_en IS NULL
      AND cerrado_por_usuario_id IS NULL AND cerrado_en IS NULL
      AND cancelado_por_usuario_id IS NULL AND cancelado_en IS NULL
      AND cancelacion_motivo IS NULL
    )
    OR (
      estado IN ('ENVIADA', 'PARCIAL', 'LIQUIDADA')
      AND enviado_por_usuario_id IS NOT NULL AND enviado_en IS NOT NULL
      AND cerrado_por_usuario_id IS NULL AND cerrado_en IS NULL
      AND cancelado_por_usuario_id IS NULL AND cancelado_en IS NULL
      AND cancelacion_motivo IS NULL
    )
    OR (
      estado = 'CERRADA'
      AND enviado_por_usuario_id IS NOT NULL AND enviado_en IS NOT NULL
      AND cerrado_por_usuario_id IS NOT NULL AND cerrado_en IS NOT NULL
      AND cancelado_por_usuario_id IS NULL AND cancelado_en IS NULL
      AND cancelacion_motivo IS NULL
    )
    OR (
      estado = 'CANCELADA'
      AND enviado_por_usuario_id IS NULL AND enviado_en IS NULL
      AND cerrado_por_usuario_id IS NULL AND cerrado_en IS NULL
      AND cancelado_por_usuario_id IS NOT NULL AND cancelado_en IS NOT NULL
      AND cancelacion_motivo IS NOT NULL
    )
  )
);

CREATE INDEX consignaciones_cliente_estado_idx
  ON consignaciones_editoriales (cliente_id, estado, creado_en DESC, id DESC);
CREATE INDEX consignaciones_tipo_estado_idx
