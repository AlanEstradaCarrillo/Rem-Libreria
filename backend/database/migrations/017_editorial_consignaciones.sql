BEGIN
  IF TG_OP='DELETE' THEN
    RAISE EXCEPTION 'Las consignaciones no se eliminan; deben cancelarse o cerrarse.'
      USING ERRCODE = '55000';
  END IF;
  IF ROW(
    NEW.id, NEW.folio, NEW.cliente_id, NEW.cliente_nombre,
