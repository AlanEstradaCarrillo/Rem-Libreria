    NEW.estado, NEW.enviado_por_usuario_id, NEW.enviado_en,
    NEW.cerrado_por_usuario_id, NEW.cerrado_en,
    NEW.cancelado_por_usuario_id, NEW.cancelado_en, NEW.cancelacion_motivo
