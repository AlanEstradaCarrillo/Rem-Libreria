-- leyendo exclusivamente movimientos para no atribuir efectivo a consignación.
CREATE OR REPLACE VIEW eventos_comerciales AS
SELECT ('POS:'||m.id)::text AS evento_clave,
       m.tipo::text AS tipo_evento,
       'POS'::text AS fuente,
       m.creado_en AS fecha_evento,
       m.id AS movimiento_id,
       m.sesion_id,
       m.caja_id,
       m.usuario_id,
       m.metodo_pago,
       m.monto AS importe,
       CASE WHEN m.tipo='VENTA' THEN m.monto ELSE -m.monto END AS importe_neto,
       v.id AS venta_id,
       NULL::bigint AS consignacion_editorial_id,
       NULL::bigint AS consignacion_operacion_id,
       v.folio,
       v.cliente_id,
       v.cliente AS cliente_nombre,
       CASE WHEN ped.canal='WEB' THEN 'WEB' ELSE 'POS' END::text AS canal,
       CASE
         WHEN v.pedido_id IS NULL THEN 'VENTA_DIRECTA'
         WHEN ped.canal='WEB' THEN 'PEDIDO_WEB'
         ELSE 'PEDIDO_INTERNO'
       END::text AS origen,
       c.nombre AS caja_nombre,
       u.nombre AS usuario,
       m.referencia,
       m.concepto
FROM movimientos m
LEFT JOIN cancelaciones_venta cv ON cv.id=m.cancelacion_id
LEFT JOIN devoluciones dev ON dev.id=m.devolucion_id
JOIN ventas v ON v.id=COALESCE(m.venta_id, cv.venta_id, dev.venta_id)
LEFT JOIN pedidos ped ON ped.id=v.pedido_id
JOIN caja c ON c.id=m.caja_id
JOIN usuarios u ON u.id=m.usuario_id
WHERE m.tipo IN ('VENTA','CANCELACION','DEVOLUCION')

UNION ALL

SELECT ('CONSIGNACION:'||o.id)::text,
       'VENTA'::text,
       'CONSIGNACION'::text,
       o.creado_en,
       NULL::integer,
       NULL::integer,
       NULL::integer,
       o.usuario_id,
       NULL::varchar(20),
       o.total,
       o.total,
       NULL::integer,
       c.id,
       o.id,
       o.folio,
       c.cliente_id,
       c.cliente_nombre,
       'CONSIGNACION'::text,
       c.tipo_comercial::text,
       NULL::varchar(80),
       u.nombre,
       o.referencia,
       ('Venta consignada de '||c.folio)::text
FROM consignacion_operaciones o
JOIN consignaciones_editoriales c ON c.id=o.consignacion_editorial_id
JOIN usuarios u ON u.id=o.usuario_id
WHERE o.tipo='VENTA';

