CREATE OR REPLACE FUNCTION validar_consignacion_conciliada(p_consignacion_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $function$
DECLARE
  v_consignacion consignaciones_editoriales%ROWTYPE;
  v_ultimo_estado VARCHAR(12);
  v_envios INTEGER;
  v_actividad INTEGER;
  v_pendiente BIGINT;
BEGIN
  SELECT * INTO v_consignacion
  FROM consignaciones_editoriales WHERE id=p_consignacion_id;
  IF NOT FOUND THEN RETURN; END IF;

  SELECT estado_nuevo INTO v_ultimo_estado
  FROM consignacion_transiciones
  WHERE consignacion_editorial_id=p_consignacion_id
  ORDER BY id DESC LIMIT 1;
  IF v_ultimo_estado IS DISTINCT FROM v_consignacion.estado THEN
    RAISE EXCEPTION 'El historial de la consignación % no coincide con su estado.', p_consignacion_id
      USING ERRCODE = '23514';
  END IF;

  SELECT COUNT(*) FILTER (WHERE tipo='ENVIO')::int,
         COUNT(*) FILTER (WHERE tipo IN ('VENTA','DEVOLUCION'))::int
  INTO v_envios, v_actividad
  FROM consignacion_operaciones
  WHERE consignacion_editorial_id=p_consignacion_id;
  SELECT COALESCE(SUM(cantidad_enviada-cantidad_vendida-cantidad_devuelta),0)
  INTO v_pendiente
  FROM consignacion_detalles
  WHERE consignacion_editorial_id=p_consignacion_id;

  IF EXISTS (
    SELECT 1
    FROM consignacion_detalles d
    LEFT JOIN (
      SELECT od.consignacion_detalle_id,
             COALESCE(SUM(od.cantidad) FILTER (WHERE o.tipo='ENVIO'),0)::int AS enviada,
             COALESCE(SUM(od.cantidad) FILTER (WHERE o.tipo='VENTA'),0)::int AS vendida,
             COALESCE(SUM(od.cantidad) FILTER (WHERE o.tipo='DEVOLUCION'),0)::int AS devuelta
      FROM consignacion_operacion_detalles od
      JOIN consignacion_operaciones o ON o.id=od.consignacion_operacion_id
      WHERE o.consignacion_editorial_id=p_consignacion_id
      GROUP BY od.consignacion_detalle_id
    ) x ON x.consignacion_detalle_id=d.id
    WHERE d.consignacion_editorial_id=p_consignacion_id
      AND (
        COALESCE(x.enviada,0) <> CASE WHEN v_consignacion.estado IN ('BORRADOR','CANCELADA')
                                     THEN 0 ELSE d.cantidad_enviada END
        OR COALESCE(x.vendida,0) <> d.cantidad_vendida
        OR COALESCE(x.devuelta,0) <> d.cantidad_devuelta
      )
  ) THEN
    RAISE EXCEPTION 'Las cantidades de la consignación % no están conciliadas.', p_consignacion_id
      USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM consignacion_operaciones o
    LEFT JOIN (
      SELECT consignacion_operacion_id,
             ROUND(COALESCE(SUM(subtotal),0),2) AS subtotal,
             ROUND(COALESCE(SUM(descuento),0),2) AS descuento,
             ROUND(COALESCE(SUM(iva),0),2) AS iva,
             ROUND(COALESCE(SUM(importe),0),2) AS total
      FROM consignacion_operacion_detalles
      GROUP BY consignacion_operacion_id
    ) d ON d.consignacion_operacion_id=o.id
    WHERE o.consignacion_editorial_id=p_consignacion_id
      AND (o.subtotal<>COALESCE(d.subtotal,0) OR o.descuento<>COALESCE(d.descuento,0)
           OR o.iva<>COALESCE(d.iva,0) OR o.total<>COALESCE(d.total,0))
  ) THEN
    RAISE EXCEPTION 'Los importes de la consignación % no están conciliados.', p_consignacion_id
      USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM consignacion_operacion_detalles od
    JOIN consignacion_operaciones o ON o.id=od.consignacion_operacion_id
    LEFT JOIN inventario_movimientos m
      ON m.detalle_consignacion_operacion_id=od.id
    WHERE o.consignacion_editorial_id=p_consignacion_id
      AND (
        m.id IS NULL OR m.usuario_id<>o.usuario_id
        OR (o.tipo='ENVIO' AND (m.tipo<>'SALIDA_CONSIGNACION'
            OR m.delta_fisico<>-od.cantidad OR m.delta_reservado<>0
            OR m.delta_consignado<>od.cantidad))
        OR (o.tipo='VENTA' AND (m.tipo<>'VENTA_CONSIGNACION'
            OR m.delta_fisico<>0 OR m.delta_reservado<>0
            OR m.delta_consignado<>-od.cantidad))
        OR (o.tipo='DEVOLUCION' AND (m.tipo<>'DEVOLUCION_CONSIGNACION'
            OR m.delta_fisico<>od.cantidad OR m.delta_reservado<>0
            OR m.delta_consignado<>-od.cantidad))
      )
  ) THEN
    RAISE EXCEPTION 'El kardex de la consignación % no está conciliado.', p_consignacion_id
      USING ERRCODE = '23514';
  END IF;

  IF v_consignacion.estado IN ('BORRADOR','CANCELADA') THEN
    IF v_envios<>0 OR v_actividad<>0 OR EXISTS (
      SELECT 1 FROM consignacion_detalles
      WHERE consignacion_editorial_id=p_consignacion_id
        AND (cantidad_vendida<>0 OR cantidad_devuelta<>0)
    ) THEN
      RAISE EXCEPTION 'La consignación % sin enviar contiene operaciones.', p_consignacion_id
        USING ERRCODE = '23514';
    END IF;
  ELSIF v_consignacion.estado='ENVIADA' THEN
    IF v_envios<>1 OR v_actividad<>0 OR v_pendiente<=0 THEN
      RAISE EXCEPTION 'La consignación enviada % no coincide con sus saldos.', p_consignacion_id
        USING ERRCODE = '23514';
    END IF;
  ELSIF v_consignacion.estado='PARCIAL' THEN
    IF v_envios<>1 OR v_actividad<=0 OR v_pendiente<=0 THEN
      RAISE EXCEPTION 'La consignación parcial % no coincide con sus saldos.', p_consignacion_id
        USING ERRCODE = '23514';
    END IF;
  ELSIF v_consignacion.estado IN ('LIQUIDADA','CERRADA') THEN
    IF v_envios<>1 OR v_actividad<=0 OR v_pendiente<>0 THEN
      RAISE EXCEPTION 'La consignación liquidada % conserva unidades pendientes.', p_consignacion_id
        USING ERRCODE = '23514';
    END IF;
  END IF;
END
$function$;

CREATE OR REPLACE FUNCTION validar_consignacion_conciliada_trg()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
  v_id BIGINT;
BEGIN
  IF TG_TABLE_NAME='consignaciones_editoriales' THEN
    v_id := CASE WHEN TG_OP='DELETE' THEN OLD.id ELSE NEW.id END;
  ELSIF TG_TABLE_NAME='consignacion_detalles' THEN
    v_id := CASE WHEN TG_OP='DELETE' THEN OLD.consignacion_editorial_id ELSE NEW.consignacion_editorial_id END;
  ELSIF TG_TABLE_NAME='consignacion_operaciones' THEN
    v_id := CASE WHEN TG_OP='DELETE' THEN OLD.consignacion_editorial_id ELSE NEW.consignacion_editorial_id END;
  ELSIF TG_TABLE_NAME='consignacion_operacion_detalles' THEN
    v_id := CASE WHEN TG_OP='DELETE' THEN OLD.consignacion_editorial_id ELSE NEW.consignacion_editorial_id END;
  ELSIF TG_TABLE_NAME='consignacion_transiciones' THEN
    v_id := CASE WHEN TG_OP='DELETE' THEN OLD.consignacion_editorial_id ELSE NEW.consignacion_editorial_id END;
  ELSE
    SELECT consignacion_editorial_id INTO v_id
    FROM consignacion_operaciones
    WHERE id=CASE WHEN TG_OP='DELETE' THEN OLD.consignacion_operacion_id
                  ELSE NEW.consignacion_operacion_id END;
  END IF;
  PERFORM validar_consignacion_conciliada(v_id);
  RETURN NULL;
END
$function$;

