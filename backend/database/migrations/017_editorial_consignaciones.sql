CREATE TABLE consignacion_detalles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consignacion_editorial_id BIGINT NOT NULL
    REFERENCES consignaciones_editoriales(id) ON DELETE RESTRICT,
  producto_id INTEGER NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
  producto_sku VARCHAR(24) NOT NULL,
  producto_titulo VARCHAR(160) NOT NULL,
  producto_isbn VARCHAR(17),
  cantidad_enviada INTEGER NOT NULL,
  cantidad_vendida INTEGER NOT NULL DEFAULT 0,
  cantidad_devuelta INTEGER NOT NULL DEFAULT 0,
  precio_lista NUMERIC(12,2) NOT NULL,
  descuento_unitario NUMERIC(12,2) NOT NULL,
  precio_unitario NUMERIC(12,2) NOT NULL,
  iva_porcentaje NUMERIC(5,2) NOT NULL,
  regla_precio_id BIGINT REFERENCES reglas_precio(id) ON DELETE RESTRICT,
  subtotal_enviado NUMERIC(14,2) NOT NULL,
  descuento_enviado NUMERIC(14,2) NOT NULL,
  iva_enviado NUMERIC(14,2) NOT NULL,
  importe_enviado NUMERIC(14,2) NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT consignacion_detalles_producto_snapshot_check CHECK (
    btrim(producto_sku) <> '' AND btrim(producto_titulo) <> ''
    AND (producto_isbn IS NULL OR btrim(producto_isbn) <> '')
  ),
  CONSTRAINT consignacion_detalles_cantidades_check CHECK (
    cantidad_enviada > 0
    AND cantidad_vendida >= 0
    AND cantidad_devuelta >= 0
    AND cantidad_vendida + cantidad_devuelta <= cantidad_enviada
  ),
  CONSTRAINT consignacion_detalles_precios_check CHECK (
    precio_lista >= 0 AND descuento_unitario >= 0 AND precio_unitario >= 0
    AND precio_unitario = precio_lista - descuento_unitario
    AND iva_porcentaje BETWEEN 0 AND 100
  ),
  CONSTRAINT consignacion_detalles_importes_check CHECK (
    importe_enviado = ROUND(precio_unitario * cantidad_enviada, 2)
    AND descuento_enviado = ROUND(descuento_unitario * cantidad_enviada, 2)
    AND iva_enviado = ROUND(importe_enviado - subtotal_enviado, 2)
    AND subtotal_enviado = ROUND(importe_enviado / (1 + iva_porcentaje / 100), 2)
  ),
  CONSTRAINT consignacion_detalles_producto_uq
    UNIQUE (consignacion_editorial_id, producto_id),
  CONSTRAINT consignacion_detalles_compuesto_uq
    UNIQUE (id, consignacion_editorial_id, producto_id)
);

CREATE INDEX consignacion_detalles_producto_idx
  ON consignacion_detalles (producto_id, consignacion_editorial_id);

CREATE TABLE consignacion_operaciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio VARCHAR(24) NOT NULL UNIQUE
    DEFAULT ('COP-' || LPAD(nextval('consignacion_operaciones_folio_seq')::text, 10, '0')),
  consignacion_editorial_id BIGINT NOT NULL
    REFERENCES consignaciones_editoriales(id) ON DELETE RESTRICT,
  tipo VARCHAR(12) NOT NULL,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  referencia VARCHAR(160),
  motivo VARCHAR(500) NOT NULL,
  subtotal NUMERIC(14,2) NOT NULL,
  descuento NUMERIC(14,2) NOT NULL,
  iva NUMERIC(14,2) NOT NULL,
  total NUMERIC(14,2) NOT NULL,
  origen_clave VARCHAR(180) NOT NULL UNIQUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT consignacion_operaciones_tipo_check CHECK (
    tipo IN ('ENVIO', 'VENTA', 'DEVOLUCION')
  ),
  CONSTRAINT consignacion_operaciones_referencia_check CHECK (
    referencia IS NULL OR btrim(referencia) <> ''
  ),
  CONSTRAINT consignacion_operaciones_venta_referencia_check CHECK (
    tipo <> 'VENTA' OR referencia IS NOT NULL
  ),
  CONSTRAINT consignacion_operaciones_motivo_check CHECK (btrim(motivo) <> ''),
  CONSTRAINT consignacion_operaciones_importes_check CHECK (
    subtotal >= 0 AND descuento >= 0 AND iva >= 0 AND total >= 0
    AND total = subtotal + iva
  ),
  CONSTRAINT consignacion_operaciones_origen_check CHECK (btrim(origen_clave) <> ''),
  CONSTRAINT consignacion_operaciones_compuesto_uq UNIQUE (id, consignacion_editorial_id)
);

CREATE INDEX consignacion_operaciones_documento_idx
  ON consignacion_operaciones (consignacion_editorial_id, creado_en, id);
CREATE INDEX consignacion_operaciones_tipo_fecha_idx
  ON consignacion_operaciones (tipo, creado_en DESC, id DESC);

CREATE TABLE consignacion_operacion_detalles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consignacion_operacion_id BIGINT NOT NULL,
  consignacion_editorial_id BIGINT NOT NULL,
  consignacion_detalle_id BIGINT NOT NULL,
  producto_id INTEGER NOT NULL,
  cantidad INTEGER NOT NULL,
  precio_lista NUMERIC(12,2) NOT NULL,
  descuento_unitario NUMERIC(12,2) NOT NULL,
  precio_unitario NUMERIC(12,2) NOT NULL,
  iva_porcentaje NUMERIC(5,2) NOT NULL,
  subtotal NUMERIC(14,2) NOT NULL,
  descuento NUMERIC(14,2) NOT NULL,
  iva NUMERIC(14,2) NOT NULL,
  importe NUMERIC(14,2) NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT consignacion_operacion_detalles_operacion_fk
    FOREIGN KEY (consignacion_operacion_id, consignacion_editorial_id)
    REFERENCES consignacion_operaciones(id, consignacion_editorial_id)
    ON DELETE RESTRICT,
  CONSTRAINT consignacion_operacion_detalles_linea_fk
    FOREIGN KEY (consignacion_detalle_id, consignacion_editorial_id, producto_id)
    REFERENCES consignacion_detalles(id, consignacion_editorial_id, producto_id)
    ON DELETE RESTRICT,
  CONSTRAINT consignacion_operacion_detalles_cantidad_check CHECK (cantidad > 0),
  CONSTRAINT consignacion_operacion_detalles_precios_check CHECK (
    precio_lista >= 0 AND descuento_unitario >= 0 AND precio_unitario >= 0
    AND precio_unitario = precio_lista - descuento_unitario
    AND iva_porcentaje BETWEEN 0 AND 100
  ),
  CONSTRAINT consignacion_operacion_detalles_importes_check CHECK (
    importe = ROUND(precio_unitario * cantidad, 2)
    AND descuento = ROUND(descuento_unitario * cantidad, 2)
    AND subtotal = ROUND(importe / (1 + iva_porcentaje / 100), 2)
    AND iva = ROUND(importe - subtotal, 2)
  ),
  CONSTRAINT consignacion_operacion_detalles_linea_uq
    UNIQUE (consignacion_operacion_id, consignacion_detalle_id),
  CONSTRAINT consignacion_operacion_detalles_compuesto_uq
    UNIQUE (id, consignacion_operacion_id, producto_id)
);

CREATE INDEX consignacion_operacion_detalles_producto_idx
  ON consignacion_operacion_detalles (producto_id, consignacion_operacion_id);

CREATE TABLE consignacion_transiciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consignacion_editorial_id BIGINT NOT NULL
    REFERENCES consignaciones_editoriales(id) ON DELETE RESTRICT,
  estado_anterior VARCHAR(12),
  estado_nuevo VARCHAR(12) NOT NULL,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  motivo VARCHAR(500) NOT NULL,
  origen_clave VARCHAR(180) NOT NULL UNIQUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT consignacion_transiciones_anterior_check CHECK (
    estado_anterior IS NULL
    OR estado_anterior IN ('BORRADOR', 'ENVIADA', 'PARCIAL', 'LIQUIDADA', 'CERRADA', 'CANCELADA')
  ),
  CONSTRAINT consignacion_transiciones_nuevo_check CHECK (
    estado_nuevo IN ('BORRADOR', 'ENVIADA', 'PARCIAL', 'LIQUIDADA', 'CERRADA', 'CANCELADA')
  ),
  CONSTRAINT consignacion_transiciones_cambio_check CHECK (
    (estado_anterior IS NULL AND estado_nuevo='BORRADOR')
    OR (estado_anterior='BORRADOR' AND estado_nuevo IN ('ENVIADA', 'CANCELADA'))
    OR (estado_anterior='ENVIADA' AND estado_nuevo IN ('PARCIAL', 'LIQUIDADA'))
    OR (estado_anterior='PARCIAL' AND estado_nuevo='LIQUIDADA')
    OR (estado_anterior='LIQUIDADA' AND estado_nuevo='CERRADA')
  ),
  CONSTRAINT consignacion_transiciones_motivo_check CHECK (btrim(motivo) <> ''),
  CONSTRAINT consignacion_transiciones_origen_check CHECK (btrim(origen_clave) <> '')
);

CREATE UNIQUE INDEX consignacion_transiciones_inicial_uq
  ON consignacion_transiciones (consignacion_editorial_id)
  WHERE estado_anterior IS NULL;
CREATE INDEX consignacion_transiciones_documento_idx
  ON consignacion_transiciones (consignacion_editorial_id, id);

