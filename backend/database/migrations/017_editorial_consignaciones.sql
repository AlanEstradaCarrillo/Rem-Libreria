CREATE OR REPLACE VIEW inventario_conciliacion AS
WITH kardex AS (
  SELECT producto_id,
         COALESCE(SUM(delta_fisico), 0)::BIGINT AS fisico_kardex,
         COALESCE(SUM(delta_reservado), 0)::BIGINT AS reservado_kardex,
         COALESCE(SUM(delta_consignado), 0)::BIGINT AS consignado_kardex
  FROM inventario_movimientos GROUP BY producto_id
), reservas AS (
  SELECT producto_id, COALESCE(SUM(cantidad), 0)::BIGINT AS reservado_activo
  FROM reservas_stock WHERE estado='ACTIVA' GROUP BY producto_id
), consignado AS (
  SELECT d.producto_id,
         COALESCE(SUM(d.cantidad_enviada-d.cantidad_vendida-d.cantidad_devuelta),0)::BIGINT
           AS consignado_activo
  FROM consignacion_detalles d
  JOIN consignaciones_editoriales c ON c.id=d.consignacion_editorial_id
  WHERE c.estado IN ('ENVIADA','PARCIAL','LIQUIDADA','CERRADA')
  GROUP BY d.producto_id
)
SELECT p.id AS producto_id, p.sku, p.titulo,
       p.stock::BIGINT AS stock_fisico,
       COALESCE(k.fisico_kardex,0) AS stock_fisico_kardex,
       p.stock::BIGINT-COALESCE(k.fisico_kardex,0) AS diferencia_fisico_kardex,
       p.stock_reservado::BIGINT AS stock_reservado,
       COALESCE(r.reservado_activo,0) AS reservado_activo,
       COALESCE(k.reservado_kardex,0) AS stock_reservado_kardex,
       p.stock_reservado::BIGINT-COALESCE(r.reservado_activo,0) AS diferencia_reservas_activas,
       p.stock_reservado::BIGINT-COALESCE(k.reservado_kardex,0) AS diferencia_reservado_kardex,
       p.stock_consignado::BIGINT AS stock_consignado,
       COALESCE(c.consignado_activo,0) AS consignado_activo,
       COALESCE(k.consignado_kardex,0) AS stock_consignado_kardex,
       p.stock_consignado::BIGINT-COALESCE(c.consignado_activo,0) AS diferencia_consignaciones_activas,
       p.stock_consignado::BIGINT-COALESCE(k.consignado_kardex,0) AS diferencia_consignado_kardex,
       p.stock_disponible::BIGINT AS stock_disponible,
       (
         p.stock=COALESCE(k.fisico_kardex,0)
         AND p.stock_reservado=COALESCE(r.reservado_activo,0)
         AND p.stock_reservado=COALESCE(k.reservado_kardex,0)
         AND p.stock_consignado=COALESCE(c.consignado_activo,0)
         AND p.stock_consignado=COALESCE(k.consignado_kardex,0)
       ) AS conciliado
FROM productos p
LEFT JOIN kardex k ON k.producto_id=p.id
LEFT JOIN reservas r ON r.producto_id=p.id
LEFT JOIN consignado c ON c.producto_id=p.id;
