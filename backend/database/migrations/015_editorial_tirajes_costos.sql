CREATE OR REPLACE FUNCTION validar_cadena_transicion_tiraje()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
  v_ultimo VARCHAR(12);
BEGIN
  SELECT estado_nuevo INTO v_ultimo
  FROM tiraje_editorial_transiciones
  WHERE tiraje_editorial_id=NEW.tiraje_editorial_id
  ORDER BY id DESC LIMIT 1;
  IF NEW.estado_anterior IS DISTINCT FROM v_ultimo THEN
    RAISE EXCEPTION 'La transición del tiraje no continúa el historial vigente.'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$function$;

CREATE TRIGGER tiraje_editorial_transiciones_cadena_trg
  BEFORE INSERT ON tiraje_editorial_transiciones
  FOR EACH ROW EXECUTE FUNCTION validar_cadena_transicion_tiraje();

CREATE OR REPLACE FUNCTION proteger_tiraje_editorial()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Los tirajes no se eliminan; deben cancelarse.' USING ERRCODE = '55000';
  END IF;
  IF NEW.id <> OLD.id OR NEW.folio <> OLD.folio
     OR NEW.obra_editorial_id <> OLD.obra_editorial_id
     OR NEW.producto_id <> OLD.producto_id
     OR NEW.obra_folio <> OLD.obra_folio OR NEW.obra_titulo <> OLD.obra_titulo
     OR NEW.producto_sku <> OLD.producto_sku
     OR NEW.producto_titulo <> OLD.producto_titulo
     OR NEW.producto_isbn IS DISTINCT FROM OLD.producto_isbn
     OR NEW.creado_por_usuario_id <> OLD.creado_por_usuario_id
     OR NEW.creado_en <> OLD.creado_en THEN
    RAISE EXCEPTION 'No se puede modificar la identidad o snapshots del tiraje.'
      USING ERRCODE = '55000';
  END IF;
  IF OLD.estado <> 'BORRADOR' THEN
    RAISE EXCEPTION 'Un tiraje finalizado es inmutable.' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$function$;

CREATE TRIGGER tirajes_editoriales_proteger_trg
  BEFORE UPDATE OR DELETE ON tirajes_editoriales
  FOR EACH ROW EXECUTE FUNCTION proteger_tiraje_editorial();

CREATE OR REPLACE FUNCTION validar_costo_tiraje_borrador()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
  v_tiraje_id BIGINT;
  v_estado VARCHAR(12);
BEGIN
  v_tiraje_id := CASE WHEN TG_OP='DELETE' THEN OLD.tiraje_editorial_id ELSE NEW.tiraje_editorial_id END;
  SELECT estado INTO v_estado
  FROM tirajes_editoriales WHERE id=v_tiraje_id FOR KEY SHARE;
  IF v_estado IS DISTINCT FROM 'BORRADOR' THEN
    RAISE EXCEPTION 'Sólo un tiraje en borrador admite cambios de costos.'
      USING ERRCODE = '55000';
  END IF;
  IF TG_OP='UPDATE' AND NEW.tiraje_editorial_id <> OLD.tiraje_editorial_id THEN
    RAISE EXCEPTION 'Un costo no puede cambiar de tiraje.' USING ERRCODE = '55000';
  END IF;
  RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END
$function$;

CREATE TRIGGER tiraje_editorial_costos_borrador_trg
  BEFORE INSERT OR UPDATE OR DELETE ON tiraje_editorial_costos
  FOR EACH ROW EXECUTE FUNCTION validar_costo_tiraje_borrador();

CREATE OR REPLACE FUNCTION validar_tiraje_editorial_conciliado(p_tiraje_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $function$
DECLARE
  v_tiraje tirajes_editoriales%ROWTYPE;
  v_ultimo_estado VARCHAR(12);
  v_costo_total NUMERIC(14,2);
  v_mov inventario_movimientos%ROWTYPE;
BEGIN
  SELECT * INTO v_tiraje FROM tirajes_editoriales WHERE id=p_tiraje_id;
  IF NOT FOUND THEN RETURN; END IF;
  SELECT estado_nuevo INTO v_ultimo_estado
  FROM tiraje_editorial_transiciones
  WHERE tiraje_editorial_id=p_tiraje_id ORDER BY id DESC LIMIT 1;
  IF v_ultimo_estado IS DISTINCT FROM v_tiraje.estado THEN
    RAISE EXCEPTION 'El historial del tiraje % no coincide con su estado.', p_tiraje_id
      USING ERRCODE = '23514';
  END IF;

  SELECT COALESCE(ROUND(SUM(monto), 2), 0) INTO v_costo_total
  FROM tiraje_editorial_costos WHERE tiraje_editorial_id=p_tiraje_id;
  SELECT * INTO v_mov FROM inventario_movimientos
  WHERE tiraje_editorial_id=p_tiraje_id;

  IF v_tiraje.estado IN ('BORRADOR', 'CANCELADO') THEN
    IF FOUND THEN
      RAISE EXCEPTION 'El tiraje % no confirmado contiene inventario.', p_tiraje_id
        USING ERRCODE = '23514';
    END IF;
    RETURN;
  END IF;

  IF v_costo_total <= 0 OR v_tiraje.costo_total_confirmado <> v_costo_total
     OR v_tiraje.costo_unitario_confirmado <> ROUND(v_costo_total / v_tiraje.cantidad, 2)
     OR v_tiraje.stock_resultante <> v_tiraje.stock_anterior + v_tiraje.cantidad
     OR v_mov.id IS NULL OR v_mov.producto_id <> v_tiraje.producto_id
     OR v_mov.tipo <> 'TIRAJE_EDITORIAL'
     OR v_mov.delta_fisico <> v_tiraje.cantidad OR v_mov.delta_reservado <> 0
     OR v_mov.stock_fisico_resultante <> v_tiraje.stock_resultante
     OR v_mov.usuario_id <> v_tiraje.confirmado_por_usuario_id THEN
    RAISE EXCEPTION 'El tiraje confirmado % no está conciliado.', p_tiraje_id
      USING ERRCODE = '23514';
  END IF;
END
$function$;

CREATE OR REPLACE FUNCTION validar_tiraje_editorial_conciliado_trg()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
  v_id BIGINT;
BEGIN
  IF TG_TABLE_NAME='tirajes_editoriales' THEN
    v_id := CASE WHEN TG_OP='DELETE' THEN OLD.id ELSE NEW.id END;
  ELSE
    v_id := CASE WHEN TG_OP='DELETE' THEN OLD.tiraje_editorial_id ELSE NEW.tiraje_editorial_id END;
  END IF;
  PERFORM validar_tiraje_editorial_conciliado(v_id);
  RETURN NULL;
END
$function$;

CREATE CONSTRAINT TRIGGER tirajes_editoriales_conciliacion_trg
  AFTER INSERT OR UPDATE ON tirajes_editoriales DEFERRABLE INITIALLY DEFERRED
