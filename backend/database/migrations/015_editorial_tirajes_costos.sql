    (estado_anterior IS NULL AND estado_nuevo = 'BORRADOR')
    OR (estado_anterior = 'BORRADOR' AND estado_nuevo IN ('CONFIRMADO', 'CANCELADO'))
  ),
  CONSTRAINT tiraje_editorial_transiciones_motivo_check CHECK (btrim(motivo) <> ''),
  CONSTRAINT tiraje_editorial_transiciones_origen_check CHECK (btrim(origen_clave) <> '')
);

