-- Tirajes editoriales y costos de producción sobre el inventario común.
-- Confirmar un tiraje incrementa productos.stock mediante el mismo kardex
-- inmutable que utilizan compras, ventas, reservas y conteos.

CREATE SEQUENCE tirajes_editoriales_folio_seq START WITH 1;

CREATE TABLE tirajes_editoriales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio VARCHAR(24) NOT NULL UNIQUE
    DEFAULT ('TIR-' || LPAD(nextval('tirajes_editoriales_folio_seq')::text, 10, '0')),
  obra_editorial_id BIGINT NOT NULL REFERENCES obras_editoriales(id) ON DELETE RESTRICT,
  producto_id INTEGER NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
  obra_folio VARCHAR(24) NOT NULL,
  obra_titulo VARCHAR(240) NOT NULL,
  producto_sku VARCHAR(24) NOT NULL,
  producto_titulo VARCHAR(160) NOT NULL,
  producto_isbn VARCHAR(17),
  cantidad INTEGER NOT NULL,
  fecha_programada DATE NOT NULL,
  moneda CHAR(3) NOT NULL DEFAULT 'MXN',
  estado VARCHAR(12) NOT NULL DEFAULT 'BORRADOR',
  notas TEXT,
  costo_total_confirmado NUMERIC(14,2),
  costo_unitario_confirmado NUMERIC(12,2),
  costo_producto_anterior NUMERIC(12,2),
  costo_producto_nuevo NUMERIC(12,2),
  stock_anterior INTEGER,
  stock_resultante INTEGER,
  creado_por_usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  confirmado_por_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  confirmado_en TIMESTAMPTZ,
  cancelado_por_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  cancelado_en TIMESTAMPTZ,
  cancelacion_motivo VARCHAR(500),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT tirajes_editoriales_obra_snapshot_check CHECK (
    btrim(obra_folio) <> '' AND btrim(obra_titulo) <> ''
  ),
  CONSTRAINT tirajes_editoriales_producto_snapshot_check CHECK (
    btrim(producto_sku) <> '' AND btrim(producto_titulo) <> ''
  ),
  CONSTRAINT tirajes_editoriales_isbn_check CHECK (
    producto_isbn IS NULL OR btrim(producto_isbn) <> ''
  ),
  CONSTRAINT tirajes_editoriales_cantidad_check CHECK (cantidad > 0),
  CONSTRAINT tirajes_editoriales_moneda_check CHECK (moneda ~ '^[A-Z]{3}$'),
  CONSTRAINT tirajes_editoriales_estado_check CHECK (
    estado IN ('BORRADOR', 'CONFIRMADO', 'CANCELADO')
  ),
  CONSTRAINT tirajes_editoriales_notas_check CHECK (
    notas IS NULL OR btrim(notas) <> ''
  ),
  CONSTRAINT tirajes_editoriales_cancelacion_motivo_check CHECK (
    cancelacion_motivo IS NULL OR btrim(cancelacion_motivo) <> ''
  ),
  CONSTRAINT tirajes_editoriales_resultado_check CHECK (
    stock_anterior IS NULL OR stock_resultante = stock_anterior + cantidad
  ),
  CONSTRAINT tirajes_editoriales_costo_check CHECK (
    costo_total_confirmado IS NULL OR (
      costo_total_confirmado > 0
      AND costo_unitario_confirmado = ROUND(costo_total_confirmado / cantidad, 2)
      AND costo_producto_anterior >= 0
      AND costo_producto_nuevo = costo_unitario_confirmado
    )
  ),
  CONSTRAINT tirajes_editoriales_efectos_estado_check CHECK (
    (
      estado = 'BORRADOR'
      AND costo_total_confirmado IS NULL AND costo_unitario_confirmado IS NULL
      AND costo_producto_anterior IS NULL AND costo_producto_nuevo IS NULL
      AND stock_anterior IS NULL AND stock_resultante IS NULL
      AND confirmado_por_usuario_id IS NULL AND confirmado_en IS NULL
      AND cancelado_por_usuario_id IS NULL AND cancelado_en IS NULL
      AND cancelacion_motivo IS NULL
    )
    OR (
      estado = 'CONFIRMADO'
      AND costo_total_confirmado IS NOT NULL AND costo_unitario_confirmado IS NOT NULL
      AND costo_producto_anterior IS NOT NULL AND costo_producto_nuevo IS NOT NULL
      AND stock_anterior IS NOT NULL AND stock_resultante IS NOT NULL
      AND confirmado_por_usuario_id IS NOT NULL AND confirmado_en IS NOT NULL
      AND cancelado_por_usuario_id IS NULL AND cancelado_en IS NULL
      AND cancelacion_motivo IS NULL
    )
    OR (
      estado = 'CANCELADO'
      AND costo_total_confirmado IS NULL AND costo_unitario_confirmado IS NULL
      AND costo_producto_anterior IS NULL AND costo_producto_nuevo IS NULL
      AND stock_anterior IS NULL AND stock_resultante IS NULL
      AND confirmado_por_usuario_id IS NULL AND confirmado_en IS NULL
      AND cancelado_por_usuario_id IS NOT NULL AND cancelado_en IS NOT NULL
      AND cancelacion_motivo IS NOT NULL
    )
  ),
  CONSTRAINT tirajes_editoriales_id_producto_uq UNIQUE (id, producto_id)
);

CREATE INDEX tirajes_editoriales_obra_estado_idx
