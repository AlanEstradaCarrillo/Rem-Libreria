CREATE OR REPLACE FUNCTION validar_cambio_reserva_stock()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Las reservas no se eliminan.' USING ERRCODE = '55000';
  END IF;
  IF ROW(NEW.pedido_id, NEW.detalle_pedido_id, NEW.producto_id, NEW.cantidad, NEW.expira_en, NEW.creado_en)
     IS DISTINCT FROM
     ROW(OLD.pedido_id, OLD.detalle_pedido_id, OLD.producto_id, OLD.cantidad, OLD.expira_en, OLD.creado_en) THEN
    RAISE EXCEPTION 'No se puede alterar el origen de una reserva.' USING ERRCODE = '55000';
  END IF;
  IF OLD.estado <> 'ACTIVA' OR NEW.estado NOT IN ('LIBERADA', 'CONSUMIDA', 'EXPIRADA') THEN
    RAISE EXCEPTION 'Transición de reserva inválida.' USING ERRCODE = '23514';
  END IF;
  NEW.finalizada_en := COALESCE(NEW.finalizada_en, NOW());
  RETURN NEW;
END
$function$;
CREATE TRIGGER reservas_stock_validar_cambio_trg
  BEFORE UPDATE OR DELETE ON reservas_stock
  FOR EACH ROW EXECUTE FUNCTION validar_cambio_reserva_stock();

CREATE OR REPLACE FUNCTION validar_transicion_pedido()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
BEGIN
  IF NEW.estado = OLD.estado THEN RETURN NEW; END IF;
  IF NOT (
    (OLD.estado = 'RESERVADO' AND NEW.estado IN ('LISTO', 'COMPLETADO', 'CANCELADO', 'EXPIRADO'))
    OR (OLD.estado = 'LISTO' AND NEW.estado IN ('COMPLETADO', 'CANCELADO', 'EXPIRADO'))
  ) THEN
    RAISE EXCEPTION 'Transición de pedido no permitida: % -> %.', OLD.estado, NEW.estado
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$function$;
CREATE TRIGGER pedidos_validar_transicion_trg
  BEFORE UPDATE OF estado ON pedidos FOR EACH ROW EXECUTE FUNCTION validar_transicion_pedido();

CREATE OR REPLACE VIEW inventario_conciliacion AS
WITH kardex AS (
  SELECT producto_id,
         COALESCE(SUM(delta_fisico), 0)::BIGINT AS fisico_kardex,
         COALESCE(SUM(delta_reservado), 0)::BIGINT AS reservado_kardex
  FROM inventario_movimientos GROUP BY producto_id
), reservas AS (
  SELECT producto_id, COALESCE(SUM(cantidad), 0)::BIGINT AS reservado_activo
  FROM reservas_stock WHERE estado = 'ACTIVA' GROUP BY producto_id
)
SELECT p.id AS producto_id, p.sku, p.titulo,
       p.stock::BIGINT AS stock_fisico,
       COALESCE(k.fisico_kardex, 0) AS stock_fisico_kardex,
       p.stock::BIGINT - COALESCE(k.fisico_kardex, 0) AS diferencia_fisico_kardex,
       p.stock_reservado::BIGINT AS stock_reservado,
       COALESCE(r.reservado_activo, 0) AS reservado_activo,
       COALESCE(k.reservado_kardex, 0) AS stock_reservado_kardex,
       p.stock_reservado::BIGINT - COALESCE(r.reservado_activo, 0) AS diferencia_reservas_activas,
       p.stock_reservado::BIGINT - COALESCE(k.reservado_kardex, 0) AS diferencia_reservado_kardex,
       p.stock_disponible::BIGINT AS stock_disponible,
       (p.stock = COALESCE(k.fisico_kardex, 0)
        AND p.stock_reservado = COALESCE(r.reservado_activo, 0)
        AND p.stock_reservado = COALESCE(k.reservado_kardex, 0)) AS conciliado
FROM productos p
LEFT JOIN kardex k ON k.producto_id = p.id
LEFT JOIN reservas r ON r.producto_id = p.id;

