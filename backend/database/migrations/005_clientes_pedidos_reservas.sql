CREATE OR REPLACE FUNCTION completar_actor_idempotencia()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
BEGIN
  IF NEW.usuario_id IS NOT NULL THEN
    NEW.actor_clave := COALESCE(NEW.actor_clave, 'USUARIO:' || NEW.usuario_id::text);
    IF NEW.actor_clave <> 'USUARIO:' || NEW.usuario_id::text THEN
      RAISE EXCEPTION 'actor_clave no corresponde al usuario.' USING ERRCODE = '23514';
    END IF;
  ELSIF NEW.actor_clave IS NULL OR NEW.actor_clave !~ '^PUBLICO:[0-9a-f]{64}$' THEN
    RAISE EXCEPTION 'Una operación pública requiere un actor opaco válido.' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$function$;
CREATE TRIGGER operaciones_idempotentes_actor_trg
  BEFORE INSERT OR UPDATE OF usuario_id, actor_clave ON operaciones_idempotentes
  FOR EACH ROW EXECUTE FUNCTION completar_actor_idempotencia();

