CREATE OR REPLACE FUNCTION proteger_snapshot_pedido()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Los pedidos son auditables y no pueden eliminarse.' USING ERRCODE = '55000';
  END IF;
  IF ROW(
    NEW.id, NEW.folio, NEW.canal, NEW.canal_precio, NEW.cliente_id,
    NEW.creado_por_usuario_id, NEW.cliente_nombre, NEW.cliente_telefono,
    NEW.cliente_email, NEW.cliente_direccion, NEW.tipo_entrega, NEW.notas,
    NEW.subtotal, NEW.descuento, NEW.iva, NEW.total, NEW.expira_en, NEW.creado_en
  ) IS DISTINCT FROM ROW(
    OLD.id, OLD.folio, OLD.canal, OLD.canal_precio, OLD.cliente_id,
    OLD.creado_por_usuario_id, OLD.cliente_nombre, OLD.cliente_telefono,
    OLD.cliente_email, OLD.cliente_direccion, OLD.tipo_entrega, OLD.notas,
    OLD.subtotal, OLD.descuento, OLD.iva, OLD.total, OLD.expira_en, OLD.creado_en
  ) THEN
    RAISE EXCEPTION 'El contenido comercial de un pedido es inmutable.' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$function$;
CREATE TRIGGER pedidos_proteger_snapshot_trg
  BEFORE UPDATE OR DELETE ON pedidos FOR EACH ROW EXECUTE FUNCTION proteger_snapshot_pedido();

CREATE OR REPLACE FUNCTION proteger_estado_pedido()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
BEGIN
  IF NEW.estado IS DISTINCT FROM OLD.estado
     AND COALESCE(current_setting('libra.aplicando_transicion_pedido', TRUE), '') <> '1' THEN
    RAISE EXCEPTION 'El estado sólo cambia mediante pedido_transiciones.' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$function$;
CREATE TRIGGER pedidos_proteger_estado_trg
  BEFORE UPDATE OF estado ON pedidos FOR EACH ROW EXECUTE FUNCTION proteger_estado_pedido();

CREATE OR REPLACE FUNCTION validar_insert_transicion_pedido()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
DECLARE
  v_estado VARCHAR(16);
BEGIN
  SELECT estado INTO v_estado FROM pedidos WHERE id = NEW.pedido_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Pedido % no encontrado.', NEW.pedido_id USING ERRCODE = '23503';
  END IF;

  IF NEW.estado_anterior IS NULL THEN
    IF v_estado <> 'RESERVADO' OR NEW.estado_nuevo <> 'RESERVADO'
       OR EXISTS (SELECT 1 FROM pedido_transiciones WHERE pedido_id = NEW.pedido_id) THEN
      RAISE EXCEPTION 'Transición inicial inválida.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
  END IF;

  IF v_estado <> NEW.estado_anterior THEN
    RAISE EXCEPTION 'El pedido está en %, no en %.', v_estado, NEW.estado_anterior
      USING ERRCODE = '40001';
  END IF;
  IF NOT (
    (NEW.estado_anterior = 'RESERVADO'
      AND NEW.estado_nuevo IN ('LISTO', 'COMPLETADO', 'CANCELADO', 'EXPIRADO'))
    OR (NEW.estado_anterior = 'LISTO'
      AND NEW.estado_nuevo IN ('COMPLETADO', 'CANCELADO', 'EXPIRADO'))
  ) THEN
    RAISE EXCEPTION 'Transición no permitida: % -> %.', NEW.estado_anterior, NEW.estado_nuevo
      USING ERRCODE = '23514';
  END IF;
  IF NEW.estado_nuevo IN ('LISTO', 'COMPLETADO') AND NEW.actor <> 'USUARIO' THEN
    RAISE EXCEPTION 'La transición requiere un usuario autenticado.' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$function$;
CREATE TRIGGER pedido_transiciones_validar_trg
  BEFORE INSERT ON pedido_transiciones FOR EACH ROW EXECUTE FUNCTION validar_insert_transicion_pedido();

CREATE OR REPLACE FUNCTION aplicar_transicion_pedido()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
DECLARE
  v_actualizados INTEGER;
BEGIN
  IF NEW.estado_anterior IS NULL THEN RETURN NULL; END IF;
  PERFORM set_config('libra.aplicando_transicion_pedido', '1', TRUE);
  UPDATE pedidos SET estado = NEW.estado_nuevo
  WHERE id = NEW.pedido_id AND estado = NEW.estado_anterior;
  GET DIAGNOSTICS v_actualizados = ROW_COUNT;
  PERFORM set_config('libra.aplicando_transicion_pedido', '0', TRUE);
  IF v_actualizados <> 1 THEN
    RAISE EXCEPTION 'El pedido cambió concurrentemente.' USING ERRCODE = '40001';
  END IF;
  RETURN NULL;
END
$function$;
CREATE TRIGGER pedido_transiciones_aplicar_trg
  AFTER INSERT ON pedido_transiciones FOR EACH ROW EXECUTE FUNCTION aplicar_transicion_pedido();

CREATE OR REPLACE FUNCTION registrar_creacion_pedido()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
BEGIN
  IF NEW.estado <> 'RESERVADO' THEN
    RAISE EXCEPTION 'Todo pedido debe iniciar RESERVADO.' USING ERRCODE = '23514';
  END IF;
  INSERT INTO pedido_transiciones (
    pedido_id, estado_anterior, estado_nuevo, actor, usuario_id, motivo, origen_clave, creado_en
  ) VALUES (
    NEW.id, NULL, 'RESERVADO',
    CASE WHEN NEW.creado_por_usuario_id IS NULL THEN 'PUBLICO' ELSE 'USUARIO' END,
    NEW.creado_por_usuario_id, 'Creación y reserva atómica del pedido.',
    'PEDIDO:' || NEW.id::text || ':CREACION', NEW.creado_en
  );
  RETURN NULL;
END
$function$;
CREATE TRIGGER pedidos_registrar_creacion_trg
  AFTER INSERT ON pedidos FOR EACH ROW EXECUTE FUNCTION registrar_creacion_pedido();

-- Conciliación diferida: ninguna transacción puede confirmar un pedido parcial.
CREATE OR REPLACE FUNCTION validar_pedido_conciliado(p_pedido_id BIGINT)
RETURNS VOID LANGUAGE plpgsql AS $function$
DECLARE
  v_pedido pedidos%ROWTYPE;
  v_total NUMERIC(12,2);
  v_descuento NUMERIC(12,2);
  v_subtotal NUMERIC(12,2);
  v_iva NUMERIC(12,2);
  v_ultimo_estado VARCHAR(16);
BEGIN
  IF p_pedido_id IS NULL THEN RETURN; END IF;
  SELECT * INTO v_pedido FROM pedidos WHERE id = p_pedido_id;
  IF NOT FOUND THEN RETURN; END IF;

  IF NOT EXISTS (SELECT 1 FROM detalle_pedidos WHERE pedido_id = p_pedido_id) THEN
    RAISE EXCEPTION 'El pedido % no contiene artículos.', p_pedido_id USING ERRCODE = '23514';
  END IF;
  IF EXISTS (
    SELECT 1 FROM detalle_pedidos d
    LEFT JOIN reservas_stock r
      ON r.pedido_id = d.pedido_id AND r.producto_id = d.producto_id
    WHERE d.pedido_id = p_pedido_id
      AND (r.id IS NULL OR r.detalle_pedido_id <> d.id OR r.cantidad <> d.cantidad
           OR r.expira_en <> v_pedido.expira_en)
  ) THEN
    RAISE EXCEPTION 'Las reservas no corresponden al detalle del pedido %.', p_pedido_id
      USING ERRCODE = '23514';
  END IF;

  SELECT ROUND(COALESCE(SUM(importe), 0), 2),
         ROUND(COALESCE(SUM(descuento_unitario * cantidad), 0), 2),
         ROUND(COALESCE(SUM(importe / (1 + iva_porcentaje / 100)), 0), 2)
  INTO v_total, v_descuento, v_subtotal
  FROM detalle_pedidos WHERE pedido_id = p_pedido_id;
  v_iva := ROUND(v_total - v_subtotal, 2);
  IF v_total <> v_pedido.total OR v_descuento <> v_pedido.descuento
     OR v_subtotal <> v_pedido.subtotal OR v_iva <> v_pedido.iva THEN
    RAISE EXCEPTION 'Los totales del pedido % no concilian.', p_pedido_id USING ERRCODE = '23514';
  END IF;

  SELECT estado_nuevo INTO v_ultimo_estado
  FROM pedido_transiciones WHERE pedido_id = p_pedido_id ORDER BY id DESC LIMIT 1;
  IF v_ultimo_estado IS DISTINCT FROM v_pedido.estado THEN
    RAISE EXCEPTION 'El historial del pedido % no concilia con su estado.', p_pedido_id
      USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1 FROM reservas_stock r
    WHERE r.pedido_id = p_pedido_id
      AND NOT EXISTS (
        SELECT 1 FROM inventario_movimientos im
        WHERE im.reserva_id = r.id AND im.pedido_id = r.pedido_id
          AND im.producto_id = r.producto_id AND im.tipo = 'RESERVA'
          AND im.delta_fisico = 0 AND im.delta_reservado = r.cantidad
      )
  ) THEN
    RAISE EXCEPTION 'Hay reservas sin alta exacta en kardex para el pedido %.', p_pedido_id
      USING ERRCODE = '23514';
  END IF;

  IF v_pedido.estado IN ('RESERVADO', 'LISTO') THEN
    IF EXISTS (SELECT 1 FROM reservas_stock WHERE pedido_id = p_pedido_id AND estado <> 'ACTIVA')
       OR EXISTS (SELECT 1 FROM ventas WHERE pedido_id = p_pedido_id)
       OR EXISTS (
         SELECT 1 FROM inventario_movimientos
         WHERE pedido_id = p_pedido_id
           AND tipo IN ('LIBERACION_RESERVA', 'EXPIRACION_RESERVA', 'CONSUMO_RESERVA')
       ) THEN
      RAISE EXCEPTION 'El pedido activo % no concilia.', p_pedido_id USING ERRCODE = '23514';
    END IF;
  ELSIF v_pedido.estado = 'COMPLETADO' THEN
    IF NOT EXISTS (SELECT 1 FROM ventas WHERE pedido_id = p_pedido_id)
       OR EXISTS (
         SELECT 1 FROM reservas_stock r
         WHERE r.pedido_id = p_pedido_id AND (
           r.estado <> 'CONSUMIDA' OR NOT EXISTS (
             SELECT 1 FROM inventario_movimientos im
             JOIN ventas v ON v.id = im.venta_id AND v.pedido_id = p_pedido_id
             WHERE im.reserva_id = r.id AND im.tipo = 'CONSUMO_RESERVA'
               AND im.delta_fisico = -r.cantidad AND im.delta_reservado = -r.cantidad
           )
         )
       ) THEN
      RAISE EXCEPTION 'El pedido completado % no concilia.', p_pedido_id USING ERRCODE = '23514';
    END IF;
  ELSIF v_pedido.estado = 'CANCELADO' THEN
    IF EXISTS (SELECT 1 FROM ventas WHERE pedido_id = p_pedido_id)
       OR EXISTS (
         SELECT 1 FROM reservas_stock r
         WHERE r.pedido_id = p_pedido_id AND (
           r.estado <> 'LIBERADA' OR NOT EXISTS (
             SELECT 1 FROM inventario_movimientos im
             WHERE im.reserva_id = r.id AND im.tipo = 'LIBERACION_RESERVA'
               AND im.delta_fisico = 0 AND im.delta_reservado = -r.cantidad
           )
         )
       ) THEN
      RAISE EXCEPTION 'El pedido cancelado % no concilia.', p_pedido_id USING ERRCODE = '23514';
    END IF;
  ELSIF v_pedido.estado = 'EXPIRADO' THEN
    IF EXISTS (SELECT 1 FROM ventas WHERE pedido_id = p_pedido_id)
       OR EXISTS (
         SELECT 1 FROM reservas_stock r
         WHERE r.pedido_id = p_pedido_id AND (
           r.estado <> 'EXPIRADA' OR NOT EXISTS (
             SELECT 1 FROM inventario_movimientos im
             WHERE im.reserva_id = r.id AND im.tipo = 'EXPIRACION_RESERVA'
               AND im.delta_fisico = 0 AND im.delta_reservado = -r.cantidad
           )
         )
       ) THEN
      RAISE EXCEPTION 'El pedido expirado % no concilia.', p_pedido_id USING ERRCODE = '23514';
    END IF;
  END IF;
END
$function$;

CREATE OR REPLACE FUNCTION validar_pedido_conciliado_trg()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
DECLARE
  v_id BIGINT;
BEGIN
  IF TG_TABLE_NAME = 'pedidos' THEN
    v_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END;
  ELSIF TG_TABLE_NAME IN ('detalle_pedidos', 'reservas_stock') THEN
    v_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.pedido_id ELSE NEW.pedido_id END;
  ELSIF TG_TABLE_NAME = 'inventario_movimientos' THEN
    v_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.pedido_id ELSE NEW.pedido_id END;
  ELSIF TG_TABLE_NAME = 'ventas' THEN
    IF TG_OP = 'DELETE' THEN v_id := OLD.pedido_id; ELSE v_id := NEW.pedido_id; END IF;
  END IF;
  PERFORM validar_pedido_conciliado(v_id);
  RETURN NULL;
END
$function$;

CREATE CONSTRAINT TRIGGER pedidos_conciliacion_trg
  AFTER INSERT OR UPDATE ON pedidos DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_pedido_conciliado_trg();
CREATE CONSTRAINT TRIGGER detalle_pedidos_conciliacion_trg
  AFTER INSERT ON detalle_pedidos DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_pedido_conciliado_trg();
CREATE CONSTRAINT TRIGGER reservas_stock_conciliacion_trg
  AFTER INSERT OR UPDATE ON reservas_stock DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_pedido_conciliado_trg();
CREATE CONSTRAINT TRIGGER inventario_pedido_conciliacion_trg
  AFTER INSERT ON inventario_movimientos DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_pedido_conciliado_trg();
CREATE CONSTRAINT TRIGGER ventas_pedido_conciliacion_trg
  AFTER INSERT OR UPDATE OR DELETE ON ventas DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validar_pedido_conciliado_trg();

CREATE OR REPLACE FUNCTION validar_armado_pedido()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
DECLARE
  v_estado VARCHAR(16);
  v_creado_en TIMESTAMPTZ;
BEGIN
  SELECT estado, creado_en INTO v_estado, v_creado_en
  FROM pedidos WHERE id = NEW.pedido_id FOR KEY SHARE;
  IF NOT FOUND OR v_estado <> 'RESERVADO' OR v_creado_en <> transaction_timestamp() THEN
    RAISE EXCEPTION 'El detalle y las reservas sólo se crean junto con el pedido.'
      USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END
$function$;
CREATE TRIGGER detalle_pedidos_validar_armado_trg
  BEFORE INSERT ON detalle_pedidos FOR EACH ROW EXECUTE FUNCTION validar_armado_pedido();
CREATE TRIGGER reservas_stock_validar_armado_trg
  BEFORE INSERT ON reservas_stock FOR EACH ROW EXECUTE FUNCTION validar_armado_pedido();
