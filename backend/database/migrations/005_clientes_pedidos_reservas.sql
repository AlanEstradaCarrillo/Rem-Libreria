-- Clientes, pedidos y reservas sobre el inventario y precios compartidos.
-- Los datos históricos no se convierten artificialmente en clientes ni pedidos.

CREATE TABLE clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL CHECK (btrim(nombre) <> ''),
  telefono VARCHAR(30),
  email VARCHAR(254),
  direccion TEXT,
  notas TEXT,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_por_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (telefono IS NULL OR btrim(telefono) <> ''),
  CHECK (email IS NULL OR btrim(email) <> ''),
  CHECK (direccion IS NULL OR btrim(direccion) <> '')
);

CREATE INDEX clientes_nombre_lower_idx ON clientes (lower(nombre));
CREATE INDEX clientes_telefono_idx ON clientes (telefono) WHERE telefono IS NOT NULL;
CREATE UNIQUE INDEX clientes_email_lower_uq
  ON clientes (lower(email)) WHERE email IS NOT NULL;
CREATE TRIGGER clientes_actualizado_en_trg
  BEFORE UPDATE ON clientes FOR EACH ROW EXECUTE FUNCTION marcar_actualizado_en();

CREATE SEQUENCE pedidos_folio_seq START WITH 1;

CREATE TABLE pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio VARCHAR(24) NOT NULL UNIQUE
    DEFAULT ('P-' || LPAD(nextval('pedidos_folio_seq')::text, 10, '0')),
  canal VARCHAR(8) NOT NULL CHECK (canal IN ('WEB', 'INTERNO')),
  canal_precio VARCHAR(3) NOT NULL CHECK (canal_precio IN ('POS', 'WEB')),
  estado VARCHAR(16) NOT NULL DEFAULT 'RESERVADO'
    CHECK (estado IN ('RESERVADO', 'LISTO', 'COMPLETADO', 'CANCELADO', 'EXPIRADO')),
  cliente_id BIGINT REFERENCES clientes(id) ON DELETE RESTRICT,
  creado_por_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  cliente_nombre VARCHAR(120) NOT NULL CHECK (btrim(cliente_nombre) <> ''),
  cliente_telefono VARCHAR(30) NOT NULL CHECK (btrim(cliente_telefono) <> ''),
  cliente_email VARCHAR(254),
  cliente_direccion TEXT,
  tipo_entrega VARCHAR(12) NOT NULL CHECK (tipo_entrega IN ('ENVIO', 'RECOLECCION')),
  notas TEXT,
  subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
  descuento NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (descuento >= 0),
  iva NUMERIC(12,2) NOT NULL CHECK (iva >= 0),
  total NUMERIC(12,2) NOT NULL CHECK (total >= 0),
  expira_en TIMESTAMPTZ NOT NULL,
  whatsapp_notificado_en TIMESTAMPTZ,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (
    (canal = 'WEB' AND canal_precio = 'WEB' AND creado_por_usuario_id IS NULL)
    OR (canal = 'INTERNO' AND canal_precio = 'POS' AND creado_por_usuario_id IS NOT NULL)
  ),
  CHECK (cliente_email IS NULL OR btrim(cliente_email) <> ''),
  CHECK (
    (tipo_entrega = 'ENVIO' AND btrim(COALESCE(cliente_direccion, '')) <> '')
    OR tipo_entrega = 'RECOLECCION'
  ),
  CHECK (total = ROUND(subtotal + iva, 2)),
  CHECK (expira_en > creado_en)
);

CREATE INDEX pedidos_estado_expiracion_idx ON pedidos (estado, expira_en);
CREATE INDEX pedidos_canal_fecha_idx ON pedidos (canal, creado_en DESC, id DESC);
CREATE INDEX pedidos_cliente_fecha_idx
  ON pedidos (cliente_id, creado_en DESC, id DESC) WHERE cliente_id IS NOT NULL;
CREATE TRIGGER pedidos_actualizado_en_trg
  BEFORE UPDATE ON pedidos FOR EACH ROW EXECUTE FUNCTION marcar_actualizado_en();

CREATE TABLE detalle_pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedidos(id) ON DELETE RESTRICT,
  producto_id INTEGER NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
  producto_sku VARCHAR(24) NOT NULL CHECK (btrim(producto_sku) <> ''),
  producto_titulo VARCHAR(160) NOT NULL CHECK (btrim(producto_titulo) <> ''),
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  precio_lista NUMERIC(12,2) NOT NULL CHECK (precio_lista >= 0),
  descuento_unitario NUMERIC(12,2) NOT NULL DEFAULT 0,
  precio_unitario NUMERIC(12,2) NOT NULL CHECK (precio_unitario >= 0),
  iva_porcentaje NUMERIC(5,2) NOT NULL CHECK (iva_porcentaje BETWEEN 0 AND 100),
  regla_precio_id BIGINT REFERENCES reglas_precio(id) ON DELETE RESTRICT,
  importe NUMERIC(12,2) NOT NULL CHECK (importe >= 0),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (pedido_id, producto_id),
  UNIQUE (id, pedido_id, producto_id),
  CHECK (descuento_unitario >= 0 AND precio_unitario = precio_lista - descuento_unitario),
  CHECK (importe = ROUND(precio_unitario * cantidad, 2))
);

CREATE INDEX detalle_pedidos_producto_idx ON detalle_pedidos (producto_id);

CREATE TABLE reservas_stock (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedidos(id) ON DELETE RESTRICT,
  detalle_pedido_id BIGINT NOT NULL,
  producto_id INTEGER NOT NULL,
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  estado VARCHAR(12) NOT NULL DEFAULT 'ACTIVA'
    CHECK (estado IN ('ACTIVA', 'LIBERADA', 'CONSUMIDA', 'EXPIRADA')),
  expira_en TIMESTAMPTZ NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  finalizada_en TIMESTAMPTZ,
  FOREIGN KEY (detalle_pedido_id, pedido_id, producto_id)
    REFERENCES detalle_pedidos(id, pedido_id, producto_id) ON DELETE RESTRICT,
  UNIQUE (pedido_id, producto_id),
  UNIQUE (detalle_pedido_id),
  UNIQUE (id, pedido_id, producto_id),
  CHECK (expira_en > creado_en),
  CHECK (
    (estado = 'ACTIVA' AND finalizada_en IS NULL)
    OR (estado <> 'ACTIVA' AND finalizada_en IS NOT NULL)
  )
);

CREATE INDEX reservas_stock_expiracion_activa_idx
  ON reservas_stock (expira_en, pedido_id) WHERE estado = 'ACTIVA';
CREATE INDEX reservas_stock_producto_estado_idx ON reservas_stock (producto_id, estado);

CREATE TABLE pedido_transiciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedidos(id) ON DELETE RESTRICT,
  estado_anterior VARCHAR(16),
  estado_nuevo VARCHAR(16) NOT NULL,
  actor VARCHAR(12) NOT NULL CHECK (actor IN ('USUARIO', 'PUBLICO', 'SISTEMA')),
  usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
  motivo VARCHAR(240) NOT NULL CHECK (btrim(motivo) <> ''),
  origen_clave VARCHAR(180) NOT NULL UNIQUE CHECK (btrim(origen_clave) <> ''),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (estado_anterior IS NULL OR estado_anterior IN (
    'RESERVADO', 'LISTO', 'COMPLETADO', 'CANCELADO', 'EXPIRADO'
  )),
  CHECK (estado_nuevo IN (
    'RESERVADO', 'LISTO', 'COMPLETADO', 'CANCELADO', 'EXPIRADO'
  )),
  CHECK (estado_anterior IS NULL OR estado_anterior <> estado_nuevo),
  CHECK (estado_anterior IS NOT NULL OR estado_nuevo = 'RESERVADO'),
  CHECK (
    (actor = 'USUARIO' AND usuario_id IS NOT NULL)
    OR (actor <> 'USUARIO' AND usuario_id IS NULL)
  )
);

CREATE INDEX pedido_transiciones_pedido_idx ON pedido_transiciones (pedido_id, id DESC);

